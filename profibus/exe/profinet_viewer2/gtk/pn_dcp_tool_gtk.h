  // Configured device reader
  std::unique_ptr<ConfiguredDeviceReader> m_configured_device_reader;

  // Device tracking
  std::vector<DCPDeviceInfo> m_current_devices;
  std::chrono::steady_clock::time_point m_last_discovery;


  // UI Creation methods
  GtkWidget* createToolbar();
  GtkWidget* createDeviceList();
  GtkWidget* createConfiguredDeviceList();
  GtkWidget* createDetailsPanel();
  GtkWidget* createStatusBar();
  GtkWidget* createLogAndProgressPanel();

  // Log and progress management
  void addLogMessage(const std::string& message);
  void addLogMessageWithTimestamp(const std::string& message);
  void scrollLogToBottom();
  void updateProgress(double fraction, const std::string& text = "");
  void hideProgress();
  void showProgress();

  // Device list management
  void addDeviceToList(const DCPDeviceInfo& device);
  void clearDeviceList();
  GtkTreeIter* findDeviceInList(const MacAddress& mac);

  // Configured device list management
  void loadConfiguredDevices();
  void populateConfiguredDeviceList();
  void clearConfiguredDeviceList();

  // Device details
  void updateDeviceDetails(const DCPDeviceInfo* device);
  void clearDeviceDetails();

  // Status management
  void updateStatus(const std::string& message);
  void updateConnectionStatus();
  void updateTopologyButtonState();

  // Event handlers
  static void onInterfaceChanged(GtkComboBox* combo, gpointer data);
  static void onConnectClicked(GtkButton* button, gpointer data);
  static void onDisconnectClicked(GtkButton* button, gpointer data);
  static void onDiscoverClicked(GtkButton* button, gpointer data);
  static void onTopologyClicked(GtkButton* button, gpointer data);

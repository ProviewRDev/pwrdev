// Cell data function for conditional coloring of DCP devices
static void dcpDeviceCellDataFunc(GtkTreeViewColumn* column,
                                 GtkCellRenderer* cell,
                                 GtkTreeModel* model,
                                 GtkTreeIter* iter,
                                 gpointer user_data)
{
  auto* gui = static_cast<ProfinetDCP::ProfinetDCPGUI*>(user_data);
  
  char* device_name = nullptr;
  char* device_ip = nullptr;
  gtk_tree_model_get(model, iter, 
                     COL_DEVICE_NAME, &device_name,
                     COL_IP_ADDRESS, &device_ip,
                     -1);
  
  if (device_name) {
    std::string configured_ip = gui->getConfiguredDeviceIP(device_name);
    
    if (!configured_ip.empty() && device_ip && configured_ip == device_ip) {
      // Device name and IP match - subtle dark green background with white text
      g_object_set(cell, "background", "#2d5a2d", "foreground", "#ffffff", nullptr);
    } else {
      // Device not configured or IP doesn't match - use default appearance
      g_object_set(cell, "background", nullptr, "foreground", nullptr, nullptr);
    }
  } else {
    // No device name - use default appearance
    g_object_set(cell, "background", nullptr, "foreground", nullptr, nullptr);
  }
  
  g_free(device_name);
  g_free(device_ip);
}

// Selection synchronization callbacks
static void onDCPDeviceSelectionChangedForSync(GtkTreeSelection* selection, gpointer data)
{
  auto* gui = static_cast<ProfinetDCP::ProfinetDCPGUI*>(data);
  
  GtkTreeIter iter;
  if (gtk_tree_selection_get_selected(selection, nullptr, &iter)) {
    char* device_name = nullptr;
    gtk_tree_model_get(GTK_TREE_MODEL(gui->getDeviceListStore()), &iter, COL_DEVICE_NAME, &device_name, -1);
    
    if (device_name) {
      gui->syncSelectionToConfiguredList(device_name);
      g_free(device_name);
    }
  }
}

static void onConfiguredDeviceSelectionChangedForSync(GtkTreeSelection* selection, gpointer data)
{
  auto* gui = static_cast<ProfinetDCP::ProfinetDCPGUI*>(data);
  
  GtkTreeIter iter;
  if (gtk_tree_selection_get_selected(selection, nullptr, &iter)) {
    char* device_name = nullptr;
    gtk_tree_model_get(GTK_TREE_MODEL(gui->getConfiguredDeviceListStore()), &iter, COL_DEVICE_NAME, &device_name, -1);
    
    if (device_name) {
      gui->syncSelectionToDCPList(device_name);
      g_free(device_name);
    }
  }
}

// ProfinetDCPWindow implementation
ProfinetDCPWindow::ProfinetDCPWindow() : m_main_window(nullptr)
{
  g_main_window = this;
  ProfinetDCP::registerLogCallback(activityLogCallback);
}

ProfinetDCPWindow::~ProfinetDCPWindow()
{
  ProfinetDCP::registerLogCallback(nullptr); // Unregister callback
  if (m_main_window && GTK_IS_WIDGET(m_main_window))
  {
    gtk_widget_destroy(m_main_window);
  }
  m_main_window = nullptr;
  g_main_window = nullptr;
}

bool ProfinetDCPWindow::create()
{
  // Create main window
  m_main_window = gtk_window_new(GTK_WINDOW_TOPLEVEL);
  gtk_window_set_title(GTK_WINDOW(m_main_window), "PROFINET DCP Tool");
  gtk_window_set_default_size(GTK_WINDOW(m_main_window), 1000,
                              800); // Increased for better device list visibility

  // Set minimum window size to prevent layout breaking
  gtk_widget_set_size_request(GTK_WIDGET(m_main_window), 900, 600); // Minimum 900x600

  gtk_window_set_position(GTK_WINDOW(m_main_window), GTK_WIN_POS_CENTER);

  // Set window icon
  gtk_window_set_icon_name(GTK_WINDOW(m_main_window), "network-workgroup");

  // Connect destroy signals
  g_signal_connect(m_main_window, "delete-event", G_CALLBACK(onDeleteEvent), this);
  g_signal_connect(m_main_window, "destroy", G_CALLBACK(onDestroy), this);

  // Create GUI controller
  m_gui_controller = std::make_unique<ProfinetDCPGUI>(m_main_window);
  if (!m_gui_controller->initialize())
  {
    return false;
  }

  // Add main widget to window
  GtkWidget* main_widget = m_gui_controller->createMainWidget();
  if (!main_widget)
  {
    return false;
  }

  gtk_container_add(GTK_CONTAINER(m_main_window), main_widget);

  return true;
}

void ProfinetDCPWindow::show()
{
  if (m_main_window)
  {
    gtk_widget_show_all(m_main_window);
  }
}

void ProfinetDCPWindow::run() const
{
  if (m_main_window)
  {
    gtk_main();
  }
}

gboolean ProfinetDCPWindow::onDeleteEvent(GtkWidget* widget, GdkEvent* event, gpointer data)
{
  // Return FALSE to allow the window to be destroyed
  return FALSE;
}

void ProfinetDCPWindow::onDestroy(GtkWidget* widget, gpointer data)
{
  // Shutdown the GUI controller
  auto* window = static_cast<ProfinetDCPWindow*>(data);
  if (window->m_gui_controller)
  {
    window->m_gui_controller->shutdown();
  }

  // Quit the main loop
  gtk_main_quit();
}

ProfinetDCPTool* ProfinetDCPWindow::getDCPTool() const
{
  return m_gui_controller ? m_gui_controller->getDCPTool() : nullptr;
}

void ProfinetDCPWindow::addLogMessage(const std::string& message)
{
  if (m_gui_controller)
  {
    m_gui_controller->addLogMessageWithTimestamp(message);
  }
}


void ProfinetDCPGUI::onConnectClicked(GtkButton* button, gpointer data)
{
  auto* gui = static_cast<ProfinetDCPGUI*>(data);

  std::string interface = gui->getSelectedInterface();
  if (interface.empty())
  {
    GTKUtils::showErrorDialog(gui->m_parent_window, "Error", "Please select a network interface");
    return;
  }

  gui->addLogMessageWithTimestamp("Connecting to interface: " + interface);

  auto result = gui->m_dcp_tool->initialize(interface);
  if (result == DCPResult::Success)
  {
    gui->m_is_connected = true;
    gui->updateConnectionStatus();
    gui->addLogMessageWithTimestamp("Successfully connected to " + interface);
  }
  else
  {
    std::string error_msg =
        "Failed to connect to interface " + interface + ": " + ProfinetDCPTool::dcpResultToString(result);
    gui->addLogMessageWithTimestamp(error_msg);

    GTKUtils::showErrorDialog(gui->m_parent_window, "Connection Error",
                              "Failed to connect to interface: " +
                                  ProfinetDCPTool::dcpResultToString(result));
  }
}


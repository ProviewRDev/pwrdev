static void onMainWidgetRealized(GtkWidget* widget, gpointer data);

GtkWidget* ProfinetDCPGUI::createMainWidget()
{
  // Create main vertical box
  m_main_widget = gtk_box_new(GTK_ORIENTATION_VERTICAL, 0);

  // Create m_toolbar
  m_toolbar = createToolbar();
  gtk_box_pack_start(GTK_BOX(m_main_widget), m_toolbar, FALSE, FALSE, 0);

  // Create vertical paned container for main content and log
  GtkWidget* vpaned = gtk_paned_new(GTK_ORIENTATION_VERTICAL);
  gtk_box_pack_start(GTK_BOX(m_main_widget), vpaned, TRUE, TRUE, 0);

  // Create horizontal paned container for device lists and details
  GtkWidget* hpaned = gtk_paned_new(GTK_ORIENTATION_HORIZONTAL);
  gtk_paned_pack1(GTK_PANED(vpaned), hpaned, TRUE, TRUE);

  // Create vertical paned container for both device lists
  GtkWidget* device_lists_paned = gtk_paned_new(GTK_ORIENTATION_VERTICAL);
  gtk_paned_pack1(GTK_PANED(hpaned), device_lists_paned, TRUE, TRUE);

  // Create discovered device list (DCP)
  GtkWidget* device_list = createDeviceList();
  gtk_paned_pack1(GTK_PANED(device_lists_paned), device_list, TRUE, TRUE);

  // Create configured device list
  GtkWidget* configured_device_list = createConfiguredDeviceList();
  gtk_paned_pack2(GTK_PANED(device_lists_paned), configured_device_list, TRUE, TRUE);

  // Create details panel
  GtkWidget* details = createDetailsPanel();
  gtk_paned_pack2(GTK_PANED(hpaned), details, FALSE, TRUE); // Allow shrinking but don't resize with window

  // Create log and progress panel
  GtkWidget* log_panel = createLogAndProgressPanel();
  gtk_paned_pack2(GTK_PANED(vpaned), log_panel, FALSE, TRUE);

  // Set proportional positions after widget is realized to work with any window size
  g_signal_connect(m_main_widget, "realize", G_CALLBACK(onMainWidgetRealized), nullptr);

  // Store paned widgets for the realize callback
  g_object_set_data(G_OBJECT(m_main_widget), "vpaned", vpaned);
  g_object_set_data(G_OBJECT(m_main_widget), "hpaned", hpaned);

  // Initialize interface combo
  populateInterfaceCombo();
  updateConnectionStatus();

  // Add initial ready message to log
  addLogMessageWithTimestamp("PROFINET DCP Tool ready");

  return m_main_widget;
}


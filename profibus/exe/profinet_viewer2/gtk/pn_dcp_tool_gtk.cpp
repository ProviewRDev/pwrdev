void DeviceConfigDialog::onDialogResponse(GtkDialog* dialog, gint response_id, gpointer data)
{
  auto* config_dialog = static_cast<DeviceConfigDialog*>(data);

  switch (response_id)
  {
  case GTK_RESPONSE_APPLY:
    config_dialog->applyConfiguration();
    break;
  case GTK_RESPONSE_CANCEL:
  default:
    // Dialog will be destroyed by show() method, just break
    break;
  }
}

void DeviceConfigDialog::applyConfiguration()
{
  if (!m_dcp_tool)
  {
    GTKUtils::showErrorDialog(m_parent_window, "Error", "No DCP tool available");
    return;
  }

  // Get values from entries
  std::string new_name = GTKUtils::getEntryText(GTK_ENTRY(m_name_entry));
  std::string new_ip = GTKUtils::getEntryText(GTK_ENTRY(m_ip_entry));
  std::string new_subnet = GTKUtils::getEntryText(GTK_ENTRY(m_subnet_entry));
  std::string new_gateway = GTKUtils::getEntryText(GTK_ENTRY(m_gateway_entry));

  // Validate inputs
  IPAddress ip, subnet, gateway;
  if (!ip.fromString(new_ip) || !subnet.fromString(new_subnet) || !gateway.fromString(new_gateway))
  {
    GTKUtils::showErrorDialog(m_parent_window, "Invalid Input", "Please enter valid IP addresses");
    return;
  }

  gtk_label_set_text(GTK_LABEL(m_status_label), "Applying configuration...");

  // Apply device name if changed
  if (new_name != m_current_device.device_name)
  {
    if (g_main_window)
    {
      g_main_window->addLogMessage("Changing device name from '" + m_current_device.device_name + "' to '" +
                                   new_name + "' for device [" + m_current_device.ip_address.toString() +
                                   "]");
    }
    auto result = m_dcp_tool->setDeviceName(m_current_device.mac_address, new_name);
    if (result == DCPResult::Success)
    {
      if (g_main_window)
      {
        g_main_window->addLogMessage("✓ Device name change successful for device [" +
                                     m_current_device.ip_address.toString() + "]");
      }
    }
    else
    {
      if (g_main_window)
      {
        g_main_window->addLogMessage("✗ Device name change failed for device [" +
                                     m_current_device.ip_address.toString() + "] - " +
                                     ProfinetDCPTool::dcpResultToString(result));
      }
      GTKUtils::showErrorDialog(m_parent_window, "Error",
                                "Failed to set device name: " + ProfinetDCPTool::dcpResultToString(result));
      return;
    }
  }

  // Apply IP configuration if changed
  if (ip.addr != m_current_device.ip_address.addr || subnet.addr != m_current_device.subnet_mask.addr ||
      gateway.addr != m_current_device.default_gateway.addr)
  {
    if (g_main_window)
    {
      g_main_window->addLogMessage("Changing IP configuration for device '" + m_current_device.device_name +
                                   "' from [IP: " + m_current_device.ip_address.toString() +
                                   ", Subnet: " + m_current_device.subnet_mask.toString() + ", GW: " +
                                   m_current_device.default_gateway.toString() + "] to [IP: " + new_ip +
                                   ", Subnet: " + new_subnet + ", GW: " + new_gateway + "]");
    }
    auto result = m_dcp_tool->setIPConfiguration(m_current_device.mac_address, ip, subnet, gateway);
    if (result == DCPResult::Success)
    {
      if (g_main_window)
      {
        g_main_window->addLogMessage("✓ IP configuration change successful for device '" +
                                     m_current_device.device_name + "'");
      }
    }
    else
    {
      if (g_main_window)
      {
        g_main_window->addLogMessage("✗ IP configuration change failed for device '" +
                                     m_current_device.device_name + "' - " +
                                     ProfinetDCPTool::dcpResultToString(result));
      }
      GTKUtils::showErrorDialog(m_parent_window, "Error",
                                "Failed to set IP configuration: " +
                                    ProfinetDCPTool::dcpResultToString(result));
      return;
    }
  }

  gtk_label_set_text(GTK_LABEL(m_status_label), "Configuration applied successfully");
  // Success is logged to activity log, no need for dialog
}


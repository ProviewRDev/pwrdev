void ProfinetDCPGUI::updateDeviceDetails(const DCPDeviceInfo* device)
{
  // Clear existing content
  GList* children = gtk_container_get_children(GTK_CONTAINER(m_details_container));
  for (GList* iter = children; iter != NULL; iter = g_list_next(iter))
  {
    gtk_widget_destroy(GTK_WIDGET(iter->data));
  }
  g_list_free(children);

  if (!device)
  {
    GtkWidget* empty_label = gtk_label_new("Select a device to view details");
    gtk_container_add(GTK_CONTAINER(m_details_container), empty_label);
    gtk_widget_show_all(m_details_container);
    return;
  }

  // Create general info page
  GtkWidget* info_grid = gtk_grid_new();
  gtk_grid_set_row_spacing(GTK_GRID(info_grid), 6);
  gtk_grid_set_column_spacing(GTK_GRID(info_grid), 12);
  gtk_style_context_add_class(gtk_widget_get_style_context(info_grid), "info-grid");

  int row = 0;

  // MAC Address
  gtk_grid_attach(GTK_GRID(info_grid), createRightAlignedLabel("MAC Address:"), 0, row, 1, 1);
  gtk_grid_attach(GTK_GRID(info_grid), createLeftAlignedLabel(device->mac_address.toString().c_str()), 1,
                  row++, 1, 1);

  // Device Name
  gtk_grid_attach(GTK_GRID(info_grid), createRightAlignedLabel("Device Name:"), 0, row, 1, 1);
  gtk_grid_attach(GTK_GRID(info_grid), createLeftAlignedLabel(device->device_name.c_str()), 1, row++, 1, 1);

  // IP Address
  gtk_grid_attach(GTK_GRID(info_grid), createRightAlignedLabel("IP Address:"), 0, row, 1, 1);
  gtk_grid_attach(GTK_GRID(info_grid), createLeftAlignedLabel(device->ip_address.toString().c_str()), 1,
                  row++, 1, 1);

  // Subnet Mask
  gtk_grid_attach(GTK_GRID(info_grid), createRightAlignedLabel("Subnet Mask:"), 0, row, 1, 1);
  gtk_grid_attach(GTK_GRID(info_grid), createLeftAlignedLabel(device->subnet_mask.toString().c_str()), 1,
                  row++, 1, 1);

  // Gateway
  gtk_grid_attach(GTK_GRID(info_grid), createRightAlignedLabel("Gateway:"), 0, row, 1, 1);
  gtk_grid_attach(GTK_GRID(info_grid), createLeftAlignedLabel(device->default_gateway.toString().c_str()), 1,
                  row++, 1, 1);

  // Vendor
  gtk_grid_attach(GTK_GRID(info_grid), createRightAlignedLabel("Vendor:"), 0, row, 1, 1);
  gtk_grid_attach(GTK_GRID(info_grid),
                  createLeftAlignedLabel(ProfinetDCPTool::vendorIdWithHexToString(device->vendor_id).c_str()),
                  1, row++, 1, 1);

  // Device ID
  gtk_grid_attach(GTK_GRID(info_grid), createRightAlignedLabel("Device ID:"), 0, row, 1, 1);
  gtk_grid_attach(GTK_GRID(info_grid),
                  createLeftAlignedLabel(
                      ProfinetDCPTool::deviceIdWithHexToString(device->vendor_id, device->device_id).c_str()),
                  1, row++, 1, 1);

  // Device Type
  if (!device->type_of_station.empty())
  {
    gtk_grid_attach(GTK_GRID(info_grid), createRightAlignedLabel("Device Type:"), 0, row, 1, 1);
    gtk_grid_attach(GTK_GRID(info_grid), createLeftAlignedLabel(device->type_of_station.c_str()), 1, row++, 1,
                    1);
  }

  // Device Description (from XML)
  if (device->vendor_id != 0 && device->device_id != 0)
  {
    std::string device_name, device_type, device_description;
    ProfinetDCPTool::getDeviceInfo(device->vendor_id, device->device_id, device_name, device_type,
                                   device_description);
    if (!device_description.empty())
    {
      // Label for "Description:"
      gtk_grid_attach(GTK_GRID(info_grid), createRightAlignedLabel("Description:"), 0, row, 1, 1);

      // Multi-line wrapping label for description text
      GtkWidget* desc_text = gtk_label_new(device_description.c_str());
      gtk_widget_set_halign(desc_text, GTK_ALIGN_START);
      gtk_widget_set_hexpand(desc_text, FALSE);
      gtk_label_set_selectable(GTK_LABEL(desc_text), TRUE);
      gtk_label_set_line_wrap(GTK_LABEL(desc_text), TRUE);
      gtk_label_set_line_wrap_mode(GTK_LABEL(desc_text), PANGO_WRAP_WORD);
      gtk_label_set_max_width_chars(GTK_LABEL(desc_text), 40);
      gtk_label_set_xalign(GTK_LABEL(desc_text), 0.0); // Align text to left edge
      gtk_grid_attach(GTK_GRID(info_grid), desc_text, 1, row++, 1, 1);
    }
  }

  // Device Role
  gtk_grid_attach(GTK_GRID(info_grid), createRightAlignedLabel("Device Role:"), 0, row, 1, 1);
  gtk_grid_attach(GTK_GRID(info_grid),
                  createLeftAlignedLabel(ProfinetDCPTool::deviceRoleToString(device->device_role).c_str()), 1,
                  row++, 1, 1);

  // Add the info grid directly to the container (no tabs)
  gtk_container_add(GTK_CONTAINER(m_details_container), info_grid);

  // Show the content
  gtk_widget_show_all(m_details_container);
}


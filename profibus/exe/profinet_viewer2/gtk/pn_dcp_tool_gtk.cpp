void addDeviceToStore(GtkListStore* store, const DCPDeviceInfo& device)
{
  GtkTreeIter iter;
  gtk_list_store_append(store, &iter);
  updateDeviceInStore(store, &iter, device);
}

void updateDeviceInStore(GtkListStore* store, GtkTreeIter* iter, const DCPDeviceInfo& device)
{
  gtk_list_store_set(store, iter, COL_MAC_ADDRESS, device.mac_address.toString().c_str(), COL_DEVICE_NAME,
                     device.device_name.c_str(), COL_IP_ADDRESS, device.ip_address.toString().c_str(),
                     COL_VENDOR, ProfinetDCPTool::vendorIdToString(device.vendor_id).c_str(), COL_DEVICE_ID,
                     ProfinetDCPTool::deviceIdToString(device.vendor_id, device.device_id).c_str(),
                     COL_DEVICE_PTR,
                     nullptr, // We'll manage this differently
                     -1);
}


void DeviceConfigDialog::resetToFactory()
{
  if (!m_dcp_tool)
  {
    GTKUtils::showErrorDialog(m_parent_window, "Error", "No DCP tool available");
    return;
  }

  // Create factory reset selection dialog
  GtkWidget* selection_dialog =
      gtk_dialog_new_with_buttons("Factory Reset Selection", GTK_WINDOW(m_dialog), GTK_DIALOG_MODAL, "_Close",
                                  GTK_RESPONSE_CANCEL, "_Reset", GTK_RESPONSE_ACCEPT, nullptr);

  if (!selection_dialog)
  {
    GTKUtils::showErrorDialog(m_parent_window, "Error", "Failed to create factory reset m_dialog");
    return;
  }

  // Add CSS style class to reset button (destructive action)
  GtkWidget* reset_accept_button =
      gtk_dialog_get_widget_for_response(GTK_DIALOG(selection_dialog), GTK_RESPONSE_ACCEPT);
  if (reset_accept_button)
  {
    gtk_style_context_add_class(gtk_widget_get_style_context(reset_accept_button), "destructive-action");
  }

  GtkWidget* content_area = gtk_dialog_get_content_area(GTK_DIALOG(selection_dialog));
  gtk_style_context_add_class(gtk_widget_get_style_context(content_area), "m_dialog-main-content");

  // Warning label
  GtkWidget* warning_label = gtk_label_new(nullptr);
  gtk_label_set_markup(
      GTK_LABEL(warning_label),
      "<span weight=\"bold\" foreground=\"red\">WARNING: This will reset the device!</span>\n"
      "Choose the appropriate reset mode for your needs:");
  gtk_label_set_line_wrap(GTK_LABEL(warning_label), TRUE);
  gtk_widget_set_margin_bottom(warning_label, 12);
  gtk_box_pack_start(GTK_BOX(content_area), warning_label, FALSE, FALSE, 0);

  // Create radio buttons for reset modes
  GSList* radio_group = nullptr;
  GtkWidget* radio_buttons[6];

  // Create first radio button (establishes the group)
  radio_buttons[0] = gtk_radio_button_new_with_label(
      nullptr, "Application Data - Reset application parameters only (least disruptive)");
  radio_group = gtk_radio_button_get_group(GTK_RADIO_BUTTON(radio_buttons[0]));

  // Create remaining buttons and add them to the same group
  radio_buttons[1] = gtk_radio_button_new_with_label(
      radio_group, "Communication - Reset IP address and communication settings (most common)");
  radio_group = gtk_radio_button_get_group(GTK_RADIO_BUTTON(radio_buttons[1]));

  radio_buttons[2] =
      gtk_radio_button_new_with_label(radio_group, "Engineering - Reset engineering/configuration data");
  radio_group = gtk_radio_button_get_group(GTK_RADIO_BUTTON(radio_buttons[2]));

  radio_buttons[3] =
      gtk_radio_button_new_with_label(radio_group, "All Data - Reset all configuration data (comprehensive)");
  radio_group = gtk_radio_button_get_group(GTK_RADIO_BUTTON(radio_buttons[3]));

  radio_buttons[4] = gtk_radio_button_new_with_label(
      radio_group, "Device - Full device reset including firmware settings (device restart)");
  radio_group = gtk_radio_button_get_group(GTK_RADIO_BUTTON(radio_buttons[4]));

  radio_buttons[5] = gtk_radio_button_new_with_label(
      radio_group, "Reset and Restore - Complete reset with restore capability (maximum reset)");

  // Set Communication as default (most common case)
  gtk_toggle_button_set_active(GTK_TOGGLE_BUTTON(radio_buttons[1]), TRUE);

  // Add radio buttons to dialog
  for (int i = 0; i < 6; i++)
  {
    gtk_widget_set_margin_start(radio_buttons[i], 12);
    gtk_widget_set_margin_bottom(radio_buttons[i], 4);
    gtk_box_pack_start(GTK_BOX(content_area), radio_buttons[i], FALSE, FALSE, 0);
  }

  // Add informational label
  GtkWidget* info_label =
      gtk_label_new("\nNote: Switch/infrastructure device resets may cause temporary network disconnection.\n"
                    "Recovery times vary: Light resets (5s), Device resets (15-20s).");
  gtk_label_set_line_wrap(GTK_LABEL(info_label), TRUE);
  gtk_widget_set_margin_top(info_label, 12);
  gtk_box_pack_start(GTK_BOX(content_area), info_label, FALSE, FALSE, 0);

  gtk_widget_show_all(content_area);

  gint response = gtk_dialog_run(GTK_DIALOG(selection_dialog));

  // Determine which reset mode was selected before destroying dialog
  int selected_mode = 1; // default to Communication
  if (response == GTK_RESPONSE_ACCEPT)
  {
    for (int i = 0; i < 6; i++)
    {
      if (gtk_toggle_button_get_active(GTK_TOGGLE_BUTTON(radio_buttons[i])))
      {
        selected_mode = i;
        break;
      }
    }
  }

  // Always destroy the m_dialog before proceeding
  gtk_widget_destroy(selection_dialog);

  // Check if user cancelled
  if (response != GTK_RESPONSE_ACCEPT)
  {
    return;
  }

  // Show final confirmation with specific reset type
  std::string reset_type_names[] = {"Application Data", "Communication", "Engineering",
                                    "All Data",         "Device",        "Reset and Restore"};

  std::string confirm_message =
      "Are you sure you want to perform a \"" + reset_type_names[selected_mode] + "\" factory reset?\n\n";

  if (selected_mode >= 3) // All Data, Device, or Reset and Restore
  {
    confirm_message += "⚠️  This is a comprehensive reset that may require significant reconfiguration!\n";
  }

  if (selected_mode >= 4) // Device or Reset and Restore
  {
    confirm_message += "⚠️  This will restart the device and may cause network disruption!\n";
  }

  GtkWidget* final_confirm =
      gtk_message_dialog_new(GTK_WINDOW(m_dialog), GTK_DIALOG_MODAL, GTK_MESSAGE_WARNING, GTK_BUTTONS_YES_NO,
                             "%s", confirm_message.c_str());

  if (!final_confirm)
  {
    GTKUtils::showErrorDialog(m_parent_window, "Error", "Failed to create confirmation m_dialog");
    return;
  }

  gint final_response = gtk_dialog_run(GTK_DIALOG(final_confirm));
  gtk_widget_destroy(final_confirm);

  if (final_response != GTK_RESPONSE_YES)
    return;

  // Log factory reset action
  if (g_main_window)
  {
    g_main_window->addLogMessage("Performing " + reset_type_names[selected_mode] +
                                 " factory reset for device: " + m_current_device.device_name + " [" +
                                 m_current_device.ip_address.toString() + "]");
  }

  // Perform the selected factory reset
  gtk_label_set_text(GTK_LABEL(m_status_label),
                     ("Performing " + reset_type_names[selected_mode] + " factory reset...").c_str());

  DCPResult result;
  switch (selected_mode)
  {
  case 0:
    result = m_dcp_tool->resetApplicationData(m_current_device.mac_address);
    break;
  case 1:
    result = m_dcp_tool->resetCommunication(m_current_device.mac_address);
    break;
  case 2:
    result = m_dcp_tool->resetEngineering(m_current_device.mac_address);
    break;
  case 3:
    result = m_dcp_tool->resetAllData(m_current_device.mac_address);
    break;
  case 4:
    result = m_dcp_tool->resetDevice(m_current_device.mac_address);
    break;
  case 5:
    result = m_dcp_tool->resetAndRestore(m_current_device.mac_address);
    break;
  default:
    result = m_dcp_tool->resetCommunication(m_current_device.mac_address);
  }

  if (result == DCPResult::Success)
  {
    if (g_main_window)
    {
      g_main_window->addLogMessage("✓ " + reset_type_names[selected_mode] +
                                   " factory reset successful for device: " + m_current_device.device_name);
    }
    gtk_label_set_text(GTK_LABEL(m_status_label), "Factory reset completed successfully");

    // Success is logged to activity log, no need for dialog
  }
  else
  {
    if (g_main_window)
    {
      g_main_window->addLogMessage("✗ " + reset_type_names[selected_mode] +
                                   " factory reset failed for device: " + m_current_device.device_name +
                                   " - " + ProfinetDCPTool::dcpResultToString(result));
    }

    gtk_label_set_text(GTK_LABEL(m_status_label), "Factory reset failed");

    std::string error_message = "Failed to perform " + reset_type_names[selected_mode] +
                                " factory reset: " + ProfinetDCPTool::dcpResultToString(result);

    if (result == DCPResult::NetworkError)
    {
      error_message +=
          "\n\nThis may be due to network interface issues (e.g., switch restart causing interface down).";
    }

    GTKUtils::showErrorDialog(m_parent_window, "Factory Reset Failed", error_message);
  }
}


// Helper function to convert IP string to comparable integer
static guint32 ipStringToInt(const std::string& ip_str)
{
  guint32 result = 0;
  std::istringstream iss(ip_str);
  std::string octet;
  int shift = 24;

  while (std::getline(iss, octet, '.') && shift >= 0)
  {
    result |= (std::stoi(octet) << shift);
    shift -= 8;
  }
  return result;
}

// Custom sort function for IP addresses
static gint compareIPAddresses(GtkTreeModel* model, GtkTreeIter* a, GtkTreeIter* b, gpointer data)
{
  gchar* ip_a = nullptr;
  gchar* ip_b = nullptr;

  gtk_tree_model_get(model, a, COL_IP_ADDRESS, &ip_a, -1);
  gtk_tree_model_get(model, b, COL_IP_ADDRESS, &ip_b, -1);

  if (!ip_a && !ip_b)
    return 0;
  if (!ip_a)
    return -1;
  if (!ip_b)
    return 1;

  guint32 int_a = ipStringToInt(std::string(ip_a));
  guint32 int_b = ipStringToInt(std::string(ip_b));

  g_free(ip_a);
  g_free(ip_b);

  if (int_a < int_b)
    return -1;
  if (int_a > int_b)
    return 1;
  return 0;
}


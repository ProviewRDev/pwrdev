std::string ProfinetDCPTool::deviceIdWithHexToString(uint16_t vendor_id, uint16_t device_id)
{
  std::string device_name = ::ProfinetDCP::deviceIdToString(vendor_id, device_id);

  // Detect name vs numeric ID
  bool is_numeric_only = true;
  for (char c : device_name)
  {
    if (!std::isdigit(c))
    {
      is_numeric_only = false;
      break;
    }
  }

  // If name exists, show name + hex
  if (!is_numeric_only && device_name != std::to_string(device_id))
  {
    char hex_buffer[16];
    snprintf(hex_buffer, sizeof(hex_buffer), " (0x%04X)", device_id);
    return device_name + hex_buffer;
  }
  else
  {
    // Just show hex format if no device name found
    char hex_buffer[16];
    snprintf(hex_buffer, sizeof(hex_buffer), "0x%04X", device_id);
    return hex_buffer;
  }
}


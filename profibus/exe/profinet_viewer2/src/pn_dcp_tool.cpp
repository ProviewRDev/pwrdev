// XML cache to avoid reloading per lookup
static pugi::xml_document* g_device_xml_cache = nullptr;
static std::string g_cached_xml_filename;

static void cleanupDeviceXML()
{
  if (g_device_xml_cache)
  {
    delete g_device_xml_cache;
    g_device_xml_cache = nullptr;
  }
  g_cached_xml_filename.clear();
}

static bool loadDeviceXML()
{
  pwr_tFileName fname;
  dcli_translate_filename(fname, "$pwr_exe/profinet_devices.xml");

#ifdef DEBUG
  std::cout << "Loading XML from: " << fname << std::endl;
#endif

  // Use cache if same file
  if (g_device_xml_cache && g_cached_xml_filename == fname)
  {
#ifdef DEBUG
    std::cout << "Using cached XML document" << std::endl;
#endif
    return true;
  }

  // Clean up existing cache
  cleanupDeviceXML();

  // Load new file
  g_device_xml_cache = new pugi::xml_document();
  pugi::xml_parse_result result = g_device_xml_cache->load_file(fname);

  if (result.status == pugi::status_ok)
  {
    g_cached_xml_filename = fname;
#ifdef DEBUG
    std::cout << "Successfully loaded XML device database" << std::endl;
#endif
    return true;
  }
  else
  {
#ifdef DEBUG
    std::cout << "Failed to load XML: " << result.description() << " at offset " << result.offset
              << std::endl;
#endif
    delete g_device_xml_cache;
    g_device_xml_cache = nullptr;
    return false;
  }
}

// Vendor ID to name via XML
static std::string vendorIdToString(uint16_t vendorId)
{
  try
  {
    if (loadDeviceXML() && g_device_xml_cache)
    {
      // Look for vendor with matching ID
      std::string xpath = "//Vendor[@ID='" + std::to_string(vendorId) + "']";
      pugi::xpath_node vendor_node = g_device_xml_cache->select_node(xpath.c_str());

      if (vendor_node.node())
      {
        const char* name = vendor_node.node().attribute("Name").value();
        if (name && strlen(name) > 0)
        {
          return std::string(name);
        }
      }
    }
  }
  catch (const std::exception& e)
  {
#ifdef DEBUG
    std::cout << "Exception in XML vendor lookup: " << e.what() << std::endl;
#endif
  }

  // Fallback to hardcoded mapping for common vendors
  switch (vendorId)
  {
  case 42:
    return "Siemens AG";
  case 674:
    return "Phoenix Contact";
  case 283:
    return "Beckhoff Automation";
  case 637:
    return "Weidmüller Interface GmbH";
  default:
    return "Unknown Vendor (" + std::to_string(vendorId) + ")";
  }
}

// Device ID to name via XML
static std::string deviceIdToString(uint16_t vendorId, uint16_t deviceId)
{
  try
  {
    if (loadDeviceXML() && g_device_xml_cache)
    {
      // Look for device with matching vendor and device ID
      std::string xpath =
          "//Vendor[@ID='" + std::to_string(vendorId) + "']//Device[@ID='" + std::to_string(deviceId) + "']";
      pugi::xpath_node device_node = g_device_xml_cache->select_node(xpath.c_str());

      if (device_node.node())
      {
        const char* name = device_node.node().attribute("Name").value();
        if (name && strlen(name) > 0)
        {
          return std::string(name);
        }
      }
    }
  }
  catch (const std::exception& e)
  {
#ifdef DEBUG
    std::cout << "Exception in XML device lookup: " << e.what() << std::endl;
#endif
  }

  // Fallback to device ID number
  return std::to_string(deviceId);
}


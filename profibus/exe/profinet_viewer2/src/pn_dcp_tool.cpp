// String conversion implementations
std::string MacAddress::toString() const
{
  std::ostringstream oss;
  oss << std::hex << std::setfill('0');
  for (size_t i = 0; i < addr.size(); ++i)
  {
    if (i > 0)
      oss << ":";
    oss << std::setw(2) << static_cast<int>(addr[i]);
  }
  return oss.str();
}

bool MacAddress::fromString(const std::string& str)
{
  if (str.length() != 17)
    return false;

  for (int i = 0; i < 6; ++i)
  {
    std::string byte_str = str.substr(i * 3, 2);
    try
    {
      addr[i] = static_cast<uint8_t>(std::stoi(byte_str, nullptr, 16));
    }
    catch (...)
    {
      return false;
    }
    if (i < 5 && str[i * 3 + 2] != ':')
      return false;
  }
  return true;
}

std::string IPAddress::toString() const
{
  std::ostringstream oss;
  oss << ((addr >> 24) & 0xFF) << "." << ((addr >> 16) & 0xFF) << "." << ((addr >> 8) & 0xFF) << "."
      << (addr & 0xFF);
  return oss.str();
}

bool IPAddress::fromString(const std::string& str)
{
  struct in_addr in_addr;
  if (inet_aton(str.c_str(), &in_addr) == 0)
  {
    return false;
  }
  addr = ntohl(in_addr.s_addr);
  return true;
}

// Helper function to parse device info from DCP frame (tool layer)
static bool parseDeviceInfoFromFrame(const DCPFrame& frame, DCPDeviceInfo& info)
{
  // Use parsed blocks from frame
  const auto& blocks = frame.getParsedBlocks();
  if (blocks.empty())
  {
    return false;
  }

  // Extract device info from parsed blocks
  for (const auto& block : blocks)
  {
    if (auto name_block = dynamic_cast<const ProfinetDCP::NameOfStationResponseBlock*>(block.get()))
    {
      info.device_name = name_block->getName();
    }
    else if (auto ip_block = dynamic_cast<const ProfinetDCP::IPAddressResponseBlock*>(block.get()))
    {
      info.ip_address = IPAddress(ip_block->getIP());
      info.subnet_mask = IPAddress(ip_block->getSubnet());
      info.default_gateway = IPAddress(ip_block->getGateway());
    }
    else if (auto device_id_block = dynamic_cast<const ProfinetDCP::DeviceIDResponseBlock*>(block.get()))
    {
      info.vendor_id = device_id_block->getVendorID();
      info.device_id = device_id_block->getDeviceID();
    }
  }

  info.mac_address = frame.getSourceMAC();

  // Populate type_of_station from XML using device_id
  if (info.vendor_id != 0 && info.device_id != 0)
  {
    std::string device_name, device_type, device_description;
    ProfinetDCPTool::getDeviceInfo(info.vendor_id, info.device_id, device_name, device_type,
                                   device_description);
    info.type_of_station = device_type;
  }

  return true;
}

// NetworkInterface implementation
NetworkInterface::NetworkInterface(const std::string& name) : m_interface_name(name), m_socket_fd(-1) {}

NetworkInterface::~NetworkInterface() { close(); }

DCPResult NetworkInterface::open()
{
  if (m_socket_fd >= 0)
  {
    close();
  }

  auto result = setupSocket();
  if (result != DCPResult::Success)
  {
    return result;
  }

  return getInterfaceInfo();
}

void NetworkInterface::close()
{
  if (m_socket_fd >= 0)
  {
    ::close(m_socket_fd);
    m_socket_fd = -1;
  }
}

DCPResult NetworkInterface::setupSocket()
{
#ifdef DEBUG
  std::cout << "Setting up socket for interface: " << m_interface_name << std::endl;
#endif

  m_socket_fd = socket(AF_PACKET, SOCK_RAW, htons(ETH_P_8021Q));
  // m_socket_fd = socket(AF_PACKET, SOCK_DGRAM, htons(ETH_P_ALL));
  if (m_socket_fd < 0)
  {
    std::cerr << "Failed to create raw socket: " << strerror(errno) << std::endl;
    return DCPResult::NetworkError;
  }

#ifdef DEBUG
  std::cout << "Socket created successfully, fd=" << m_socket_fd << std::endl;
#endif

  struct ifreq ifr;
  std::strncpy(ifr.ifr_name, m_interface_name.c_str(), IFNAMSIZ - 1);
  ifr.ifr_name[IFNAMSIZ - 1] = '\0';

  if (ioctl(m_socket_fd, SIOCGIFINDEX, &ifr) < 0)
  {
    std::cerr << "Failed to get interface index for " << m_interface_name << ": " << strerror(errno)
              << std::endl;
    ::close(m_socket_fd);
    m_socket_fd = -1;
    return DCPResult::NetworkError;
  }

#ifdef DEBUG
  std::cout << "Interface index: " << ifr.ifr_ifindex << std::endl;
#endif

  struct sockaddr_ll sll;
  std::memset(&sll, 0, sizeof(sll));
  sll.sll_family = AF_PACKET;
  sll.sll_protocol = htons(ETH_P_ALL); // Receive all, filter in application
  sll.sll_ifindex = ifr.ifr_ifindex;

  if (bind(m_socket_fd, reinterpret_cast<struct sockaddr*>(&sll), sizeof(sll)) < 0)
  {
    std::cerr << "Failed to bind socket: " << strerror(errno) << std::endl;
    ::close(m_socket_fd);
    m_socket_fd = -1;
    return DCPResult::NetworkError;
  }

#ifdef DEBUG
  std::cout << "Socket bound successfully to interface " << m_interface_name << std::endl;
#endif

  return DCPResult::Success;
}

DCPResult NetworkInterface::getInterfaceInfo()
{
  struct ifreq ifr;
  std::strncpy(ifr.ifr_name, m_interface_name.c_str(), IFNAMSIZ - 1);
  ifr.ifr_name[IFNAMSIZ - 1] = '\0';

  if (ioctl(m_socket_fd, SIOCGIFHWADDR, &ifr) < 0)
  {
    return DCPResult::NetworkError;
  }

  std::copy(reinterpret_cast<uint8_t*>(ifr.ifr_hwaddr.sa_data),
            reinterpret_cast<uint8_t*>(ifr.ifr_hwaddr.sa_data) + 6, m_interface_mac.addr.begin());

  return DCPResult::Success;
}

DCPResult NetworkInterface::sendFrame(const DCPFrame& frame)
{
  if (m_socket_fd < 0)
  {
    std::cerr << "Socket not open for sending" << std::endl;
    return DCPResult::NetworkError;
  }

  // Check interface connection before trying to send
  auto connection_result = checkInterfaceConnection();
  if (connection_result != DCPResult::Success)
    return connection_result;

  auto frame_data = frame.serialize();
#ifdef DEBUG
  std::cout << "Sending DCP frame, size: " << frame_data.size() << " bytes" << std::endl;
#endif

  ssize_t sent = send(m_socket_fd, frame_data.data(), frame_data.size(), 0);
  if (sent < 0)
  {
    std::cerr << "Failed to send frame: " << strerror(errno) << std::endl;
    // Check if the error is due to interface going down
    if (errno == ENETDOWN || errno == ENETUNREACH || errno == EHOSTUNREACH)
    {
      logMessage("Network interface appears to be down");
#ifdef DEBUG
      std::cerr << "Network interface appears to be down" << std::endl;
#endif
    }
    return DCPResult::NetworkError;
  }
  else if (static_cast<size_t>(sent) != frame_data.size())
  {
    std::cerr << "Partial send: " << sent << " of " << frame_data.size() << " bytes" << std::endl;
    return DCPResult::NetworkError;
  }

#ifdef DEBUG
  std::cout << "DCP frame sent successfully (" << sent << " bytes)" << std::endl;
#endif
  return DCPResult::Success;
}

DCPResult NetworkInterface::receiveFrame(DCPFrame& frame, std::chrono::milliseconds timeout)
{
  if (m_socket_fd < 0)
  {
#ifdef DEBUG
    std::cout << "receiveFrame: socket not open" << std::endl;
#endif
    return DCPResult::NetworkError;
  }

  // Check interface connection
  auto connection_result = checkInterfaceConnection();
  if (connection_result != DCPResult::Success)
    return connection_result;

  fd_set read_fds;
  FD_ZERO(&read_fds);
  FD_SET(m_socket_fd, &read_fds);

  struct timeval tv;
  tv.tv_sec = timeout.count() / 1000;
  tv.tv_usec = (timeout.count() % 1000) * 1000;

#ifdef DEBUG
  std::cout << "receiveFrame: waiting for data with timeout " << timeout.count() << "ms" << std::endl;
#endif
  int ready = select(m_socket_fd + 1, &read_fds, nullptr, nullptr, &tv);
  if (ready <= 0)
  {
    if (ready == 0)
    {
#ifdef DEBUG
      std::cout << "receiveFrame: timeout" << std::endl;
#endif
    }
    else
    {
#ifdef DEBUG
      std::cout << "receiveFrame: select error: " << strerror(errno) << std::endl;
#endif
    }
    return (ready == 0) ? DCPResult::Timeout : DCPResult::NetworkError;
  }

#ifdef DEBUG
  std::cout << "receiveFrame: data available, reading..." << std::endl;
#endif
  std::vector<uint8_t> buffer(MAX_FRAME_SIZE);
  ssize_t received = recv(m_socket_fd, buffer.data(), buffer.size(), 0);

  if (received <= 0)
  {
#ifdef DEBUG
    std::cout << "receiveFrame: recv failed: " << strerror(errno) << std::endl;
#endif
    // Check if the error is due to interface going down
    if (errno == ENETDOWN || errno == ENETUNREACH || errno == EHOSTUNREACH)
    {
      logMessage("Network interface appears to be down during receive");
#ifdef DEBUG
      std::cerr << "Network interface appears to be down during receive" << std::endl;
#endif
    }
    return DCPResult::NetworkError;
  }

#ifdef DEBUG
  std::cout << "receiveFrame: received " << received << " bytes" << std::endl;
#endif

#ifdef DEBUG
  // Print received frame (debug)
  std::cout << "Received frame: ";
  for (int i = 0; i < std::min(received, (ssize_t)32); i++)
  {
    printf("%02X ", buffer[i]);
  }
  std::cout << std::endl;
#endif

  buffer.resize(received);

  // Since socket is configured for 802.1Q only, we can make assumptions:
  // - All frames are VLAN-tagged (802.1Q)
  // - Frame structure: [Ethernet Header (14)] + [VLAN Tag (4)] + [Payload]
  // - PROFINET header starts at offset 18

  if (received < 20) // Minimum: 14 (Ethernet) + 4 (VLAN) + 2 (FrameID)
  {
#ifdef DEBUG
    std::cout << "receiveFrame: VLAN frame too small (" << received << " bytes)" << std::endl;
#endif
    return DCPResult::Timeout;
  }

  // Extract EtherType from VLAN-tagged frame (offset 12 since kernel strips Ethernet preamble and priority)
  uint16_t ethertype_be;
  std::memcpy(&ethertype_be, buffer.data() + 12, 2);
  uint16_t ethertype = ntohs(ethertype_be);

  // Quick EtherType filter - reject non-PROFINET frames
  if (ethertype != ETHERTYPE_PROFINET)
  {
#ifdef DEBUG
    std::cout << "receiveFrame: ignoring non-PROFINET frame (ethertype=0x" << std::hex << ethertype
              << std::dec << ")" << std::endl;
#endif
    return DCPResult::Timeout;
  }

  // Extract FrameID from PROFINET header (always at offset 14 for 802.1Q)
  uint16_t frame_id_be;
  std::memcpy(&frame_id_be, buffer.data() + 14, 2);
  uint16_t frame_id = ntohs(frame_id_be);

  // Filter FrameIDs - only accept DCP frames
  if (frame_id != static_cast<uint16_t>(FrameID::GET_SET) &&
      frame_id != static_cast<uint16_t>(FrameID::IDENTIFY_REQUEST) &&
      frame_id != static_cast<uint16_t>(FrameID::IDENTIFY_RESPONSE))
  {
#ifdef DEBUG
    std::cout << "receiveFrame: ignoring non-DCP PROFINET frame (FrameID=0x" << std::hex << frame_id
              << std::dec << "), filtering out cyclic data" << std::endl;
#endif
    return DCPResult::Timeout; // Continue waiting for DCP frames
  }

#ifdef DEBUG
  std::cout << "receiveFrame: DCP frame detected (FrameID=0x" << std::hex << frame_id << std::dec
            << "), proceeding with deserialization" << std::endl;
#endif

  if (!frame.deserialize(buffer))
  {
#ifdef DEBUG
    std::cout << "receiveFrame: failed to deserialize DCP frame" << std::endl;
#endif
    return DCPResult::InvalidResponse;
  }

#ifdef DEBUG
  std::cout << "receiveFrame: successfully deserialized DCP frame" << std::endl;
#endif
  return DCPResult::Success;
}

bool NetworkInterface::isInterfaceUp() const
{
  struct ifreq ifr;
  int temp_fd = socket(AF_INET, SOCK_DGRAM, 0);
  if (temp_fd < 0)
    return false;

  strncpy(ifr.ifr_name, m_interface_name.c_str(), IFNAMSIZ - 1);
  ifr.ifr_name[IFNAMSIZ - 1] = '\0';

  bool is_up = false;
  if (ioctl(temp_fd, SIOCGIFFLAGS, &ifr) == 0)
  {
    is_up = (ifr.ifr_flags & IFF_UP) && (ifr.ifr_flags & IFF_RUNNING);
  }

  ::close(temp_fd);
  return is_up;
}

DCPResult NetworkInterface::checkInterfaceConnection()
{
  if (!isInterfaceUp())
  {
    logMessage("Interface " + m_interface_name + " is down or not running");
#ifdef DEBUG
    std::cerr << "Interface " << m_interface_name << " is down or not running" << std::endl;
#endif
    return DCPResult::NetworkError;
  }
  return DCPResult::Success;
}

// ProfinetDCPTool::Impl implementation
ProfinetDCPTool::Impl::Impl() = default;

ProfinetDCPTool::Impl::~Impl() { shutdown(); }

DCPResult ProfinetDCPTool::Impl::initialize(const std::string& interface_name)
{
  shutdown(); // Clean up any existing state

  network_interface = std::make_unique<NetworkInterface>(interface_name);
  return network_interface->open();
}

void ProfinetDCPTool::Impl::shutdown()
{
  if (discovery_running)
  {
    discovery_running = false;
    if (discovery_thread.joinable())
    {
      discovery_thread.join();
    }
  }

  if (network_interface)
  {
    network_interface->close();
    network_interface.reset();
  }

  std::lock_guard<std::mutex> lock(devices_mutex);
  known_devices.clear();
}

DCPResult ProfinetDCPTool::Impl::sendRequestAndWaitResponse(const DCPFrame& request, DCPFrame& response,
                                                            std::chrono::milliseconds timeout)
{
  if (!network_interface)
    return DCPResult::NetworkError;

  auto result = network_interface->sendFrame(request);
  if (result != DCPResult::Success)
  {
    return result;
  }

  auto start_time = std::chrono::steady_clock::now();

  while (std::chrono::steady_clock::now() - start_time < timeout)
  {
    auto remaining_time = timeout - std::chrono::duration_cast<std::chrono::milliseconds>(
                                        std::chrono::steady_clock::now() - start_time);

    result = network_interface->receiveFrame(response, remaining_time);
    if (result == DCPResult::Success)
    {
      // Check if this is a response for our transaction
      if (response.getTransactionId() == request.getTransactionId())
      {
#ifdef DEBUG
        std::cout << "Received matching DCP response for transaction " << request.getTransactionId()
                  << std::endl;
#endif
        return DCPResult::Success;
      }
      else
      {
        std::cout << "Received DCP frame with different transaction ID (got " << response.getTransactionId()
                  << ", expected " << request.getTransactionId() << "), continuing to wait" << std::endl;
        continue;
      }
    }
    else if (result == DCPResult::Timeout)
    {
      continue; // Keep waiting, might have been a non-DCP frame
    }
    else
    {
      return result;
    }
  }

  return DCPResult::Timeout;
}


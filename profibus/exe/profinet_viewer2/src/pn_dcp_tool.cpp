void ProfinetDCPTool::getDeviceInfo(uint16_t vendor_id, uint16_t device_id, std::string& device_name,
                                    std::string& device_type, std::string& device_description)
{
  if (!loadDeviceXML())
  {
    device_name = "Unknown Device";
    device_type = "Unknown Type";
    device_description = "";
    return;
  }

  pugi::xml_node devices = g_device_xml_cache->child("ProfinetDevices");
  pugi::xpath_variable_set vars;
  vars.add("VendorID", pugi::xpath_type_number);
  vars.add("DeviceID", pugi::xpath_type_number);
  vars.set("VendorID", static_cast<double>(vendor_id));
  vars.set("DeviceID", static_cast<double>(device_id));
  pugi::xml_node device =
      devices.select_node("Vendor[@ID = number($VendorID)]/Device[@ID = number($DeviceID)]", &vars).node();

  if (device)
  {
    device_name = device.attribute("Name").as_string();
    device_type = device.attribute("Type").as_string();
    device_description = device.attribute("Description").as_string();
    return;
  }

  // Fallback if device not found
  device_name = "Unknown Device";
  device_type = "Unknown Type";
  device_description = "";
}


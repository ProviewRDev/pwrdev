void ProfinetDCPTool::discoverDevicesAsync(DeviceDiscoveredCallback device_callback,
                                           OperationCompleteCallback complete_callback,
                                           ProgressCallback progress_callback,
                                           std::chrono::milliseconds timeout)
{
  if (!pImpl->network_interface)
  {
    if (complete_callback)
    {
      complete_callback(DCPResult::NetworkError, "Network interface not available");
    }
    return;
  }

  // Start discovery in a separate thread to avoid blocking the UI
  std::thread(
      [this, device_callback, complete_callback, progress_callback, timeout]()
      {
        try
        {
          // Send broadcast identify request
          DCPFrame request;
          request.setDestination(DCP_MULTICAST_MAC);
          request.setSource(pImpl->network_interface->getInterfaceMAC());
          request.setFrameType(DCPFrame::FrameType::Request);
          request.setServiceType(DCPFrame::ServiceType::Identify);
          request.setTransactionId(pImpl->getNextTransactionId());
          request.addAllOption();

          if (progress_callback)
          {
            progress_callback(5, "Sending discovery request...");
          }

          // Send the request
          DCPResult send_result = pImpl->network_interface->sendFrame(request);
          if (send_result != DCPResult::Success)
          {
            if (complete_callback)
            {
              complete_callback(send_result, "Failed to send discovery request");
            }
            return;
          }

          if (progress_callback)
          {
            progress_callback(10, "Listening for responses...");
          }

          // Process responses as they come in
          auto start_time = std::chrono::steady_clock::now();
          auto last_progress_update = start_time;
          std::set<MacAddress> discovered_devices;
          int device_count = 0;

          while (true)
          {
            auto current_time = std::chrono::steady_clock::now();
            auto elapsed = std::chrono::duration_cast<std::chrono::milliseconds>(current_time - start_time);

            if (elapsed >= timeout)
            {
              break;
            }

            // Calculate remaining timeout
            auto remaining = timeout - elapsed;

            // Try to receive a response with shorter timeout to allow progress updates
            DCPFrame response;
            DCPResult result = pImpl->network_interface->receiveFrame(
                response, std::min(remaining, std::chrono::milliseconds(100)));

            if (result == DCPResult::Success)
            {
              // Check if this is an identify response
              if (response.getFrameType() == DCPFrame::FrameType::Response &&
                  response.getServiceType() == DCPFrame::ServiceType::Identify)
              {

                MacAddress device_mac = response.getSourceMAC();

                // Only process new devices
                auto [it, inserted] = discovered_devices.insert(device_mac);
                if (inserted)
                {
                  device_count++;

                  // Parse device information from the response
                  DCPDeviceInfo device_info;
                  if (parseDeviceInfoFromFrame(response, device_info))
                  {
                    // Call the device discovered callback immediately
                    if (device_callback)
                    {
                      device_callback(device_info);
                    }

                    // Update progress immediately when device found
                    if (progress_callback)
                    {
                      double time_progress =
                          static_cast<double>(elapsed.count()) / static_cast<double>(timeout.count());
                      double progress = 0.10 + (0.85 * time_progress); // 10% to 95%
                      int percent = static_cast<int>(std::min(progress * 100, 95.0));

                      std::string message = "Found " + std::to_string(device_count) + " device(s)";
                      progress_callback(percent, message);

                      last_progress_update = current_time; // Update the timer
                    }
                  }
                }
              }
            }
            else if (result != DCPResult::Timeout)
            {
              // Real error occurred
              if (complete_callback)
              {
                complete_callback(result, "Error receiving responses");
              }
              return;
            }

            // Update progress smoothly every 200ms
            auto time_since_last_update =
                std::chrono::duration_cast<std::chrono::milliseconds>(current_time - last_progress_update);

            if (progress_callback && time_since_last_update >= std::chrono::milliseconds(200))
            {
              // Calculate progress as percentage of time elapsed (10% to 95%)
              double time_progress =
                  static_cast<double>(elapsed.count()) / static_cast<double>(timeout.count());
              double progress = 0.10 + (0.85 * time_progress);                // Scale from 10% to 95%
              int percent = static_cast<int>(std::min(progress * 100, 95.0)); // Cap at 95% until complete

              std::string message = "Listening... Found " + std::to_string(device_count) + " device(s)";
              progress_callback(percent, message);

              last_progress_update = current_time;
            }
          }

          // Discovery complete
          if (progress_callback)
          {
            progress_callback(100,
                              "Discovery complete - Found " + std::to_string(device_count) + " device(s)");
          }

          if (complete_callback)
          {
            complete_callback(DCPResult::Success, "Discovery completed successfully");
          }
        }
        catch (const std::exception& e)
        {
          if (complete_callback)
          {
            complete_callback(DCPResult::NetworkError,
                              std::string("Exception during discovery: ") + e.what());
          }
        }
      })
      .detach(); // Detach the thread so it runs independently
}

std::vector<std::string> ProfinetDCPTool::getAvailableInterfaces()
{
  std::vector<std::string> interfaces;

  struct ifaddrs* ifaddr;
  if (getifaddrs(&ifaddr) == -1)
  {
    return interfaces;
  }

  for (struct ifaddrs* ifa = ifaddr; ifa != nullptr; ifa = ifa->ifa_next)
  {
    if (ifa->ifa_addr && ifa->ifa_addr->sa_family == AF_PACKET)
    {
      std::string name = ifa->ifa_name;
      if (std::find(interfaces.begin(), interfaces.end(), name) == interfaces.end())
      {
        interfaces.push_back(name);
      }
    }
  }

  freeifaddrs(ifaddr);
  std::sort(interfaces.begin(), interfaces.end());

  return interfaces;
}


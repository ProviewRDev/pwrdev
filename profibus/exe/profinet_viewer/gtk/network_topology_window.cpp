void NetworkTopologyWindow::onApplyLayoutClicked(GtkButton* button, gpointer user_data)
{
  NetworkTopologyWindow* window = static_cast<NetworkTopologyWindow*>(user_data);

  // Toggle between start and stop
  if (window->m_layout_running)
  {
    // Stop the running layout
    window->m_layout_stop_requested = true;
    window->addLogMessage("Layout algorithm stopped by user");
    return;
  }

  if (window->m_current_graph.nodes.empty())
  {
    window->addLogMessage("No topology available for layout. Please discover network topology first.");
    return;
  }

  // Join any existing thread before starting a new one
  if (window->m_layout_thread && window->m_layout_thread->joinable())
  {
    window->m_layout_thread->join();
  }

  // Reset stop flag and start layout
  window->m_layout_stop_requested = false;
  window->addLogMessage("Starting spring layout algorithm...");

  // Create and store the layout thread
  window->m_layout_thread = std::make_unique<std::thread>(
      [window]()
      {
        try
        {
          // Make a copy of the current graph for layout
          TopologyGraph graph = window->m_current_graph;

          // Apply spring layout with high max iterations - algorithm converges when equilibrium is reached
          int max_iterations = 5000;
          window->applySpringLayout(graph, max_iterations);

          // Update the current graph and redraw from main thread (only if not stopped)
          if (!window->m_layout_stop_requested)
          {
            g_idle_add(
                [](gpointer user_data) -> gboolean
                {
                  auto* data = static_cast<std::pair<NetworkTopologyWindow*, TopologyGraph*>*>(user_data);
                  NetworkTopologyWindow* win = data->first;
                  TopologyGraph* layoutGraph = data->second;

                  // Update the current graph with the laid-out positions
                  win->m_current_graph = *layoutGraph;
                  win->addLogMessage("Spring layout completed successfully");
                  gtk_widget_queue_draw(win->m_drawing_area);

                  delete layoutGraph;
                  delete data;
                  return G_SOURCE_REMOVE;
                },
                new std::pair<NetworkTopologyWindow*, TopologyGraph*>(window, new TopologyGraph(graph)));
          }
        }
        catch (const std::exception& e)
        {
          g_idle_add(
              [](gpointer user_data) -> gboolean
              {
                NetworkTopologyWindow* win = static_cast<NetworkTopologyWindow*>(user_data);
                win->addLogMessage("Layout application failed");
                win->m_layout_running = false;
                return G_SOURCE_REMOVE;
              },
              window);
        }
      });
}


gboolean NetworkTopologyWindow::onMotionNotify(GtkWidget* widget, GdkEventMotion* event, gpointer user_data)
{
  NetworkTopologyWindow* window = static_cast<NetworkTopologyWindow*>(user_data);

  if (window->m_dragging && !window->m_dragging_node)
  {
    // Pan the view
    double dx = event->x - window->m_last_mouse_x;
    double dy = event->y - window->m_last_mouse_y;

    window->m_pan_x += dx;
    window->m_pan_y += dy;

    gtk_widget_queue_draw(widget);
  }
  else if (window->m_dragging_node && window->m_selected_node != SIZE_MAX)
  {
    // Move selected node
    double dx = event->x - window->m_last_mouse_x;
    double dy = event->y - window->m_last_mouse_y;

    // Convert to world coordinates
    double world_dx = dx / window->m_zoom_factor;
    double world_dy = dy / window->m_zoom_factor;

    // Find the selected node and update its position
    size_t current_index = 0;
    for (auto& [ip, node] : window->m_current_graph.nodes)
    {
      if (current_index == window->m_selected_node)
      {
        node.x += world_dx;
        node.y += world_dy;

        // No bounds constraints - infinite canvas allows free movement
        break;
      }
      current_index++;
    }

    gtk_widget_queue_draw(widget);
  }

  // Check for node hovering for tooltips (only when not dragging)
  if (!window->m_dragging && !window->m_dragging_node)
  {
    size_t hovered_node = window->findNodeUnderMouse(event->x, event->y);

    if (hovered_node != window->m_hovered_node)
    {
      window->m_hovered_node = hovered_node;

      // Update tooltip text and visibility
      if (hovered_node != SIZE_MAX)
      {
        // Find the device info for the hovered node
        size_t current_index = 0;
        for (const auto& [ip, node] : window->m_current_graph.nodes)
        {
          if (current_index == hovered_node)
          {
            // Use system description from node (much simpler!)
            if (!node.sys_desc.empty())
            {
              window->m_tooltip_text = node.sys_desc;
              window->m_tooltip_visible = true;
            }
            else
            {
              window->m_tooltip_text = "Device: " + (node.device_name.empty() ? ip : node.device_name);
              window->m_tooltip_visible = true;
            }
            break;
          }
          current_index++;
        }
      }
      else
      {
        window->m_tooltip_visible = false;
        window->m_tooltip_text.clear();
      }

      // Queue redraw to show/hide tooltip
      gtk_widget_queue_draw(widget);
    }
  }

  window->m_last_mouse_x = event->x;
  window->m_last_mouse_y = event->y;

  return TRUE;
}


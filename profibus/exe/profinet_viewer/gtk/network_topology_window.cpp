std::string NetworkTopologyWindow::cleanPortLabel(const std::string& raw_port_id)
{
  // Parse LLDP data formats
  // "STRING: \"port-001\"" -> "port-001"
  // "Hex-STRING: AA 00 04 00 22 14" -> "AA:00:04:00:22:14"

  std::string cleaned = raw_port_id;

  // Handle STRING format: STRING: "port-name"
  size_t string_pos = cleaned.find("STRING: \"");
  if (string_pos != std::string::npos)
  {
    size_t start = string_pos + 9; // Length of "STRING: \""
    size_t end = cleaned.find("\"", start);
    if (end != std::string::npos)
    {
      return cleaned.substr(start, end - start);
    }
  }

  // Handle Hex-STRING format: Hex-STRING: AA 00 04 00 22 14
  size_t hex_pos = cleaned.find("Hex-STRING: ");
  if (hex_pos != std::string::npos)
  {
    size_t start = hex_pos + 12; // Length of "Hex-STRING: "
    std::string hex_part = cleaned.substr(start);
    // Replace spaces with colons for MAC address format
    std::replace(hex_part.begin(), hex_part.end(), ' ', ':');
    return hex_part;
  }

  // If no special format detected, return as-is (already clean)
  return cleaned;
}

std::vector<NetworkTopologyWindow::LabelInfo>
NetworkTopologyWindow::resolveCollisions(std::vector<LabelInfo>& labels)
{
  const int max_iterations = 10;
  const double offset_step = 5.0; // How much to adjust label_offset when they collide

  for (int iteration = 0; iteration < max_iterations; ++iteration)
  {
    bool had_collisions = false;

    // Check each label against all others
    for (size_t i = 0; i < labels.size(); ++i)
    {
      for (size_t j = i + 1; j < labels.size(); ++j)
      {
        if (labels[i].overlaps(labels[j]))
        {
          had_collisions = true;

          // Only move the second label (j) further away from its node along its line
          // Keep the first label (i) in its original position
          // Decrease label_offset (more negative) to move further from node
          labels[j].label_offset -= offset_step;

          // Update position based on new offset
          labels[j].updatePosition();
        }
      }
    }

    // If no collisions detected, we're done
    if (!had_collisions)
      break;
  }

  return labels;
}

void NetworkTopologyWindow::drawLabel(cairo_t* cr, const LabelInfo& label)
{
  // Get precise text metrics for proper centering
  cairo_text_extents_t extents;
  cairo_text_extents(cr, label.text.c_str(), &extents);

  // Draw background rectangle with dark theme colors
  if (label.selected_local)
  {
    // Darker background for selected node's local port
    cairo_set_source_rgba(cr, 0.2, 0.4, 0.6, 0.8);
  }
  else if (label.selected_remote)
  {
    // Darker background for remote port connected to selected
    cairo_set_source_rgba(cr, 0.2, 0.6, 0.2, 0.8);
  }
  else
  {
    // Dark background for non-selected connections
    cairo_set_source_rgba(cr, 0.15, 0.15, 0.2, 0.8);
  }

  cairo_rectangle(cr, label.left(), label.top(), label.width + 4, label.height + 4);
  cairo_fill(cr);

  // Draw text with light colors for dark background
  if (label.selected_local)
  {
    cairo_set_source_rgb(cr, 0.8, 0.9, 1.0); // Light blue text
  }
  else if (label.selected_remote)
  {
    cairo_set_source_rgb(cr, 0.8, 1.0, 0.8); // Light green text
  }
  else
  {
    cairo_set_source_rgb(cr, 0.85, 0.9, 1.0); // Light text for dark background
  }

  // Center text alignment for precise positioning
  // Use simple approach: center horizontally and position baseline slightly below center
  double text_x = label.x - extents.width / 2;
  double text_y = label.y - extents.y_bearing - extents.height / 2;

  cairo_move_to(cr, text_x, text_y);
  cairo_show_text(cr, label.text.c_str());
}

void NetworkTopologyWindow::drawTooltip(cairo_t* cr)
{
  if (m_tooltip_text.empty() || m_hovered_node == SIZE_MAX)
    return;

  // Position tooltip centered horizontally above mouse cursor
  double tooltip_x, tooltip_y;

  // Measure text dimensions for tooltip sizing
  cairo_text_extents_t extents;
  cairo_select_font_face(cr, "Sans", CAIRO_FONT_SLANT_NORMAL, CAIRO_FONT_WEIGHT_NORMAL);
  cairo_set_font_size(cr, 11.0);
  cairo_text_extents(cr, m_tooltip_text.c_str(), &extents);

  // Tooltip dimensions with padding
  double padding = 8.0;
  double tooltip_width = extents.width + 2.0 * padding;
  double tooltip_height = extents.height + 2.0 * padding;

  // Position tooltip in upper right corner (widget coordinates)
  GtkAllocation allocation;
  gtk_widget_get_allocation(m_drawing_area, &allocation);

  double margin = 10.0;                 // Margin from edge (increased for visibility)
  double effective_top_margin = margin; // Adjusted if allocation.y < 0

  // If allocation has negative Y, we need to add extra margin to avoid clipping
  if (allocation.y < 0)
  {
    effective_top_margin = margin + std::abs(allocation.y);
  }

  tooltip_x = allocation.width - tooltip_width - margin; // Right side with margin
  tooltip_y = effective_top_margin;                      // Top edge of rectangle (not bottom)

  // Draw tooltip background
  cairo_set_source_rgba(cr, 1.0, 1.0, 0.9, 0.95); // Light yellow background
  cairo_rectangle(cr, tooltip_x, tooltip_y, tooltip_width, tooltip_height);
  cairo_fill(cr);

  // Draw tooltip border
  cairo_set_source_rgb(cr, 0.6, 0.6, 0.6);
  cairo_set_line_width(cr, 1.0);
  cairo_rectangle(cr, tooltip_x, tooltip_y, tooltip_width, tooltip_height);
  cairo_stroke(cr);

  // Draw tooltip text (position baseline properly within rectangle)
  cairo_set_source_rgb(cr, 0.0, 0.0, 0.0);
  double text_x = tooltip_x + padding;
  double text_y = tooltip_y + padding + extents.height; // padding from top + text height
  cairo_move_to(cr, text_x, text_y);
  cairo_show_text(cr, m_tooltip_text.c_str());
}

std::pair<double, double> NetworkTopologyWindow::calculateNodeEdgeIntersection(const TopologyNode& from,
                                                                               const TopologyNode& to)
{
  // Node dimensions (accounting for rounded corners)
  double width = 120.0;
  double height = 80.0;
  double radius = 8.0; // Same radius as used in drawNode

  // Use smaller rectangle to avoid rounded corners
  double effective_width = width - 2.0 * radius;
  double effective_height = height - 2.0 * radius;

  // Calculate direction vector
  double dx = to.x - from.x;
  double dy = to.y - from.y;
  double length = std::sqrt(dx * dx + dy * dy);

  if (length == 0)
  {
    return {from.x, from.y};
  }

  // Normalize direction
  dx /= length;
  dy /= length;

  // Calculate intersection with smaller rectangle edge (avoids rounded corners)
  double half_width = effective_width / 2.0;
  double half_height = effective_height / 2.0;

  // Calculate the intersection with each edge and find the closest one
  double t_right = (dx > 0) ? half_width / dx : std::numeric_limits<double>::infinity();
  double t_left = (dx < 0) ? -half_width / dx : std::numeric_limits<double>::infinity();
  double t_bottom = (dy > 0) ? half_height / dy : std::numeric_limits<double>::infinity();
  double t_top = (dy < 0) ? -half_height / dy : std::numeric_limits<double>::infinity();

  // Find the minimum positive t (closest intersection)
  double t = std::min({t_right, t_left, t_bottom, t_top});

  // Calculate intersection point
  double intersect_x = from.x + t * dx;
  double intersect_y = from.y + t * dy;

  return {intersect_x, intersect_y};
}


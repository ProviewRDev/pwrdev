NetworkTopologyWindow::NetworkTopologyWindow(GtkWidget* parent, const std::vector<DCPDeviceInfo>& devices)
    : m_parent_window(parent), m_topology_window(nullptr), m_drawing_area(nullptr), m_toolbar(nullptr),
      m_layout_button(nullptr), m_log_frame(nullptr), m_log_scrolled_window(nullptr),
      m_log_text_view(nullptr), m_log_buffer(nullptr),
      m_topology_crawler(std::make_unique<TopologyCrawler>("public")), m_devices(devices),
      m_crawling_in_progress(false), m_zoom_factor(1.0), m_pan_x(0.0), m_pan_y(0.0), m_canvas_width(1200.0),
      m_canvas_height(800.0), m_dragging(false), m_dragging_node(false), m_last_mouse_x(0.0),
      m_last_mouse_y(0.0), m_selected_node(SIZE_MAX), m_hovered_node(SIZE_MAX), m_tooltip_visible(false),
      m_current_iteration(0), m_current_mean_speed(0.0), m_layout_running(false),
      m_layout_stop_requested(false), m_layout_thread(nullptr)
{
  // Register log callback to redirect crawler messages to activity log (thread-safe)
  m_topology_crawler->set_log_callback([this](const std::string& message)
                                       { this->addLogMessageThreadSafe(message); });

  createTopologyWindow();
}

NetworkTopologyWindow::~NetworkTopologyWindow()
{
  // Stop any running layout algorithm
  m_layout_stop_requested = true;
  m_layout_running = false;

  // Wait for layout thread to finish before destroying the window
  if (m_layout_thread && m_layout_thread->joinable())
  {
    m_layout_thread->join();
  }

  // Process any remaining GTK events to ensure all g_idle_add callbacks are handled
  // before we destroy the widgets
  while (gtk_events_pending())
  {
    gtk_main_iteration();
  }

  if (m_topology_window)
  {
    gtk_widget_destroy(m_topology_window);
  }
}

void NetworkTopologyWindow::show()
{
  if (m_topology_window)
  {
    gtk_widget_show_all(m_topology_window);
    gtk_window_present(GTK_WINDOW(m_topology_window));

    // Auto-start LLDP discovery on first show
    startLLDPDiscovery();
  }
}

void NetworkTopologyWindow::createTopologyWindow()
{
  m_topology_window = gtk_window_new(GTK_WINDOW_TOPLEVEL);
  gtk_window_set_title(GTK_WINDOW(m_topology_window), "Network Topology - LLDP Discovery");
  gtk_window_set_default_size(GTK_WINDOW(m_topology_window), 1200, 800);
  gtk_window_set_position(GTK_WINDOW(m_topology_window), GTK_WIN_POS_CENTER);

  if (m_parent_window)
  {
    gtk_window_set_transient_for(GTK_WINDOW(m_topology_window), GTK_WINDOW(m_parent_window));
  }

  // Create main container
  GtkWidget* vbox = gtk_box_new(GTK_ORIENTATION_VERTICAL, 0);
  gtk_container_add(GTK_CONTAINER(m_topology_window), vbox);

  // Create toolbar
  createToolbar();
  gtk_box_pack_start(GTK_BOX(vbox), m_toolbar, FALSE, FALSE, 0);

  // Create paned container for drawing area and log
  GtkWidget* paned = gtk_paned_new(GTK_ORIENTATION_VERTICAL);
  gtk_box_pack_start(GTK_BOX(vbox), paned, TRUE, TRUE, 0);

  // Create drawing area
  createDrawingArea();
  gtk_paned_pack1(GTK_PANED(paned), m_drawing_area, TRUE, TRUE);

  // Create log panel
  createLogPanel();
  gtk_paned_pack2(GTK_PANED(paned), m_log_frame, FALSE, FALSE);

  // Set paned position (70% for drawing, 30% for log)
  gtk_paned_set_position(GTK_PANED(paned), 560);

  setupEventHandlers();

  addLogMessage("Network topology window initialized");
  addLogMessage("Use 'Refresh LLDP' to discover network topology");
}


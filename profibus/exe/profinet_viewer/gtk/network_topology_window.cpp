void NetworkTopologyWindow::startLLDPDiscovery()
{
  if (m_crawling_in_progress)
  {
    addLogMessage("LLDP discovery already in progress");
    return;
  }

  m_crawling_in_progress = true;
  addLogMessageWithTimestamp("Starting LLDP network discovery...");

  // Run discovery in a separate thread to avoid blocking the UI
  std::thread(
      [this]()
      {
        try
        {
          // Get seed IPs from existing devices
          std::vector<std::string> seed_ips;
          for (const auto& device : m_devices)
          {
            // Use actual IP address from DCP discovery
            std::string ip_addr = device.ip_address.toString();
            if (!ip_addr.empty() && ip_addr != "0.0.0.0")
            {
              seed_ips.push_back(ip_addr);
            }
          }

          // If no devices, use a default range
          if (seed_ips.empty())
          {
            addLogMessageThreadSafe("No devices supplied from DCP tool for LLDP discovery");
            return;
          }

          // Convert PROFINET devices to topology DeviceInfo format for subnet filtering
          std::vector<::TopologyDeviceInfo> topology_devices; // Use global DeviceInfo from topology-crawler.h
          for (const auto& device : m_devices)
          {
            std::string ip_addr = device.ip_address.toString();
            if (!ip_addr.empty() && ip_addr != "0.0.0.0")
            {
              ::TopologyDeviceInfo topo_device; // Use global DeviceInfo
              topo_device.device_name = device.device_name;
              topo_device.ip_address = ip_addr;                        // string to string
              topo_device.subnet_mask = device.subnet_mask.toString(); // string to string
              topo_device.vendor_id = device.vendor_id;
              topo_device.device_id = device.device_id;
              topo_device.mac_address = device.mac_address.toString(); // string to string
              // sys_desc, device_type, device_vendor, neighbors remain empty for seed devices
              topology_devices.push_back(topo_device);
            }
          }

          // Perform LLDP discovery with subnet filtering
          m_topology_crawler->crawl_from_profinet_devices(topology_devices);

          // Create graph from topology data
          TopologyGraph graph = createGraphFromTopology();

          // Apply spring layout for better visualization
          // Use high max iterations - algorithm will converge early when equilibrium is reached
          int max_iterations = 5000;
          applySpringLayout(graph, max_iterations);

          // Update the current graph
          m_current_graph = graph;

          // Update UI from main thread
          g_idle_add(
              [](gpointer user_data) -> gboolean
              {
                NetworkTopologyWindow* window = static_cast<NetworkTopologyWindow*>(user_data);
                window->m_crawling_in_progress = false;
                window->addLogMessageWithTimestamp("LLDP discovery completed successfully");

                // Automatically reset view to center and frame all discovered nodes
                window->resetView();

                gtk_widget_queue_draw(window->m_drawing_area);
                return G_SOURCE_REMOVE;
              },
              this);
        }
        catch (const std::exception& e)
        {
          // Handle errors
          std::string error_msg = "LLDP discovery failed: " + std::string(e.what());
          g_idle_add(
              [](gpointer user_data) -> gboolean
              {
                NetworkTopologyWindow* window = static_cast<NetworkTopologyWindow*>(user_data);
                window->m_crawling_in_progress = false;
                window->addLogMessageWithTimestamp("LLDP discovery failed");
                return G_SOURCE_REMOVE;
              },
              this);
        }
      })
      .detach();
}

void NetworkTopologyWindow::buildTopologyFromLLDP() { startLLDPDiscovery(); }

void NetworkTopologyWindow::refreshTopology()
{
  // Create a fresh TopologyCrawler instance to ensure clean discovery
  // This clears any cached topology and visited nodes from previous crawls
  m_topology_crawler = std::make_unique<TopologyCrawler>("public");

  // Register log callback to redirect crawler messages to activity log (thread-safe)
  m_topology_crawler->set_log_callback([this](const std::string& message)
                                       { this->addLogMessageThreadSafe(message); });

  // Clear current graph to show fresh discovery
  m_current_graph.nodes.clear();
  m_current_graph.edges.clear();

  // Start fresh LLDP discovery
  buildTopologyFromLLDP();
}

// Drawing functions
void NetworkTopologyWindow::drawTopology(cairo_t* cr)
{
  // Save transform state
  cairo_save(cr);

  // Clear background with dark theme
  cairo_set_source_rgb(cr, 0.08, 0.09, 0.12);
  cairo_paint(cr);

  // No grid for infinite canvas
  // drawGrid(cr);

  // Apply zoom and pan transforms
  cairo_scale(cr, m_zoom_factor, m_zoom_factor);
  cairo_translate(cr, m_pan_x / m_zoom_factor, m_pan_y / m_zoom_factor);

  // Draw edge lines first (so they appear behind nodes)
  for (const auto& edge : m_current_graph.edges)
  {
    drawEdgeLine(cr, edge);
  }

  // Draw nodes (over the edge lines)
  size_t node_index = 0;
  for (const auto& [ip, node] : m_current_graph.nodes)
  {
    drawNode(cr, node, node_index);
    node_index++;
  }

  // Collect all edge labels first, then resolve collisions and draw
  std::vector<LabelInfo> all_labels;

  // Set up font for text measurements
  cairo_select_font_face(cr, "Sans", CAIRO_FONT_SLANT_NORMAL, CAIRO_FONT_WEIGHT_NORMAL);
  cairo_set_font_size(cr, 8);

  for (const auto& edge : m_current_graph.edges)
  {
    // Find source and destination nodes
    auto from_it = m_current_graph.nodes.find(edge.from_ip);
    auto to_it = m_current_graph.nodes.find(edge.to_ip);

    if (from_it == m_current_graph.nodes.end() || to_it == m_current_graph.nodes.end())
      continue;

    const TopologyNode& from = from_it->second;
    const TopologyNode& to = to_it->second;

    // Determine if this edge is connected to the selected node
    bool is_connected_to_selected = false;
    bool selected_is_from = false;

    if (m_selected_node != SIZE_MAX)
    {
      size_t current_node_index = 0;
      for (const auto& [ip, node] : m_current_graph.nodes)
      {
        if (current_node_index == m_selected_node)
        {
          if (ip == edge.from_ip)
          {
            is_connected_to_selected = true;
            selected_is_from = true;
          }
          else if (ip == edge.to_ip)
          {
            is_connected_to_selected = true;
            selected_is_from = false;
          }
          break;
        }
        current_node_index++;
      }
    }

    // Calculate actual line endpoints
    auto from_edge = calculateNodeEdgeIntersection(from, to);
    auto to_edge = calculateNodeEdgeIntersection(to, from);

    // Calculate vector from edge to edge for positioning
    double dx = to_edge.first - from_edge.first;
    double dy = to_edge.second - from_edge.second;
    double length = std::sqrt(dx * dx + dy * dy);

    if (length > 0)
    {
      // Normalize direction vector
      dx /= length;
      dy /= length;

      // Calculate perpendicular vector for offset (rotated 90 degrees)
      double perp_x = -dy;
      double perp_y = dx;

      // Offset distances
      double label_offset = -5.0; // Distance away from line endpoint
      // No perpendicular offset - labels positioned directly on line vector

      // Add 'from' port label to collection
      if (!edge.from_port.port_id.empty())
      {
        std::string clean_from_label = cleanPortLabel(edge.from_port.port_id);
        cairo_text_extents_t extents;
        cairo_text_extents(cr, clean_from_label.c_str(), &extents);

        LabelInfo label;
        label.width = extents.width;
        label.height = extents.height;
        label.line_dx = dx;
        label.line_dy = dy;
        label.perp_x = perp_x;
        label.perp_y = perp_y;
        label.edge_x = from_edge.first;
        label.edge_y = from_edge.second;
        label.label_offset = label_offset;
        label.text_offset = 0.0;
        label.text = clean_from_label;
        label.is_from = true;
        label.selected_local = (is_connected_to_selected && selected_is_from);
        label.selected_remote = (is_connected_to_selected && !selected_is_from);

        // Calculate initial position
        label.updatePosition();

        all_labels.push_back(label);
      }

      // Add 'to' port label to collection
      if (!edge.to_port.port_id.empty())
      {
        std::string clean_to_label = cleanPortLabel(edge.to_port.port_id);
        cairo_text_extents_t extents;
        cairo_text_extents(cr, clean_to_label.c_str(), &extents);

        LabelInfo label;
        label.width = extents.width;
        label.height = extents.height;
        label.line_dx = dx;
        label.line_dy = dy;
        label.perp_x = perp_x;
        label.perp_y = perp_y;
        label.edge_x = to_edge.first;
        label.edge_y = to_edge.second;
        label.label_offset = label_offset;
        label.text_offset = 0.0; // No perpendicular offset - on line vector
        label.text = clean_to_label;
        label.is_from = false;
        label.selected_local = (is_connected_to_selected && !selected_is_from);
        label.selected_remote = (is_connected_to_selected && selected_is_from);

        // Calculate initial position
        label.updatePosition();

        all_labels.push_back(label);
      }
    }
  }

  // Resolve collisions and draw all labels
  auto resolved_labels = resolveCollisions(all_labels);
  for (const auto& label : resolved_labels)
  {
    drawLabel(cr, label);
  }

  // Restore to widget coordinates
  cairo_restore(cr);

  // Display layout algorithm status information
  if (m_layout_running)
  {
    // Draw semi-transparent background for better text visibility
    cairo_set_source_rgba(cr, 0.0, 0.0, 0.0, 0.7); // Semi-transparent black
    cairo_rectangle(cr, 8, 8, 420, 50);            // Background rectangle
    cairo_fill(cr);

    cairo_select_font_face(cr, "Sans", CAIRO_FONT_SLANT_NORMAL, CAIRO_FONT_WEIGHT_BOLD);
    cairo_set_font_size(cr, 14);
    cairo_set_source_rgb(cr, 0.9, 0.95, 1.0); // Light text for readability

    // Display iteration, mean speed, and convergence goal (adjust Y for toolbar)
    char buf[192];
    snprintf(buf, sizeof(buf), "Iter: %d   Mean speed: %.3f   Goal: < 0.200", m_current_iteration,
             m_current_mean_speed);
    cairo_move_to(cr, 12, 80); // Moved down from 22 to 30
    cairo_show_text(cr, buf);

    // Show progress towards convergence
    cairo_set_font_size(cr, 12);
    if (m_current_mean_speed < 0.2)
    {
      cairo_set_source_rgb(cr, 0.3, 1.0, 0.3); // Green when converged
      cairo_move_to(cr, 12, 100);              // Moved down from 42 to 50
      cairo_show_text(cr, "✓ CONVERGED - Algorithm Stable!");

      // Green dot indicator
      cairo_arc(cr, 380, 24, 6, 0, 2 * M_PI); // Moved down from 16 to 24
      cairo_fill(cr);
    }
    else
    {
      cairo_set_source_rgb(cr, 1.0, 0.8, 0.3);                             // Yellow while running
      double progress = std::min(1.0, (2.0 - m_current_mean_speed) / 1.8); // Progress from 2.0 to 0.2
      snprintf(buf, sizeof(buf), "Converging... %.1f%% complete", progress * 100);
      cairo_move_to(cr, 12, 50); // Moved down from 42 to 50
      cairo_show_text(cr, buf);
    }
  }

  // Draw tooltip if visible
  if (m_tooltip_visible && !m_tooltip_text.empty())
  {
    drawTooltip(cr);
  }
}

void NetworkTopologyWindow::drawNode(cairo_t* cr, const TopologyNode& node, size_t node_index)
{
  // Node dimensions
  double width = 120.0;
  double height = 80.0;
  double radius = 8.0;
  bool is_selected = (node_index == m_selected_node);

  // Node position
  double x = node.x - width / 2;
  double y = node.y - height / 2;

  // Draw node background (rounded rectangle)
  cairo_new_sub_path(cr);
  cairo_arc(cr, x + width - radius, y + radius, radius, -M_PI / 2, 0);
  cairo_arc(cr, x + width - radius, y + height - radius, radius, 0, M_PI / 2);
  cairo_arc(cr, x + radius, y + height - radius, radius, M_PI / 2, M_PI);
  cairo_arc(cr, x + radius, y + radius, radius, M_PI, 3 * M_PI / 2);
  cairo_close_path(cr);

  // Set node colors based on device type
  if (is_selected)
  {
    cairo_set_source_rgb(cr, 0.3, 0.8, 1.0); // Brighter blue for selected node
  }
  else
  {
    // Standard blue color for PROFINET devices
    cairo_set_source_rgb(cr, 0.2, 0.6, 1.0);
  }
  cairo_fill_preserve(cr);

  // Draw border with enhanced styling for selected node
  if (is_selected)
  {
    cairo_set_source_rgb(cr, 0.0, 0.4, 0.8); // Dark blue border for selected
    cairo_set_line_width(cr, 3.0);           // Thicker border
  }
  else
  {
    cairo_set_source_rgb(cr, 0.3, 0.3, 0.3); // Normal border
    cairo_set_line_width(cr, 2.0);
  }
  cairo_stroke(cr);

  // Draw device name with light text
  cairo_set_source_rgb(cr, 0.85, 0.9, 1.0);
  cairo_select_font_face(cr, "Sans", CAIRO_FONT_SLANT_NORMAL, CAIRO_FONT_WEIGHT_NORMAL);
  cairo_set_font_size(cr, 9);

  cairo_text_extents_t extents;
  std::string display_name = node.device_name.empty() ? node.ip : node.device_name;
  cairo_text_extents(cr, display_name.c_str(), &extents);

  cairo_move_to(cr, node.x - extents.width / 2, node.y - 5);
  cairo_show_text(cr, display_name.c_str());

  // Draw IP address with smaller font
  cairo_set_font_size(cr, 8);
  cairo_text_extents(cr, node.ip.c_str(), &extents);
  cairo_move_to(cr, node.x - extents.width / 2, node.y + 8);
  cairo_show_text(cr, node.ip.c_str());
}

void NetworkTopologyWindow::drawEdgeLine(cairo_t* cr, const TopologyEdge& edge)
{
  // Find source and destination nodes
  auto from_it = m_current_graph.nodes.find(edge.from_ip);
  auto to_it = m_current_graph.nodes.find(edge.to_ip);

  if (from_it == m_current_graph.nodes.end() || to_it == m_current_graph.nodes.end())
  {
    return;
  }

  const TopologyNode& from = from_it->second;
  const TopologyNode& to = to_it->second;

  // Calculate intersection points at node edges
  auto from_edge = calculateNodeEdgeIntersection(from, to);
  auto to_edge = calculateNodeEdgeIntersection(to, from);

  // Draw connection lines with transparency
  cairo_set_source_rgba(cr, 0.7, 0.8, 0.9, 0.25);
  cairo_set_line_width(cr, 1.0);
  cairo_move_to(cr, from_edge.first, from_edge.second);
  cairo_line_to(cr, to_edge.first, to_edge.second);
  cairo_stroke(cr);
}


void NetworkTopologyWindow::exportToFile()
{
  // Check if there's a topology to export
  if (m_current_graph.nodes.empty())
  {
    addLogMessage("No topology available to export. Please discover network topology first.");
    return;
  }

  // Show file chooser dialog
  GtkWidget* dialog = gtk_file_chooser_dialog_new("Export Topology", GTK_WINDOW(m_topology_window),
                                                  GTK_FILE_CHOOSER_ACTION_SAVE, "Cancel", GTK_RESPONSE_CANCEL,
                                                  "Save", GTK_RESPONSE_ACCEPT, NULL);

  // Set default filename
  gtk_file_chooser_set_current_name(GTK_FILE_CHOOSER(dialog), "topology.png");

  // Add PNG filter
  GtkFileFilter* png_filter = gtk_file_filter_new();
  gtk_file_filter_set_name(png_filter, "PNG Images (*.png)");
  gtk_file_filter_add_pattern(png_filter, "*.png");
  gtk_file_chooser_add_filter(GTK_FILE_CHOOSER(dialog), png_filter);

  // Add SVG filter
  GtkFileFilter* svg_filter = gtk_file_filter_new();
  gtk_file_filter_set_name(svg_filter, "SVG Images (*.svg)");
  gtk_file_filter_add_pattern(svg_filter, "*.svg");
  gtk_file_chooser_add_filter(GTK_FILE_CHOOSER(dialog), svg_filter);

  // Add "All files" filter
  GtkFileFilter* all_filter = gtk_file_filter_new();
  gtk_file_filter_set_name(all_filter, "All files");
  gtk_file_filter_add_pattern(all_filter, "*");
  gtk_file_chooser_add_filter(GTK_FILE_CHOOSER(dialog), all_filter);

  gint result = gtk_dialog_run(GTK_DIALOG(dialog));

  if (result == GTK_RESPONSE_ACCEPT)
  {
    gchar* filename = gtk_file_chooser_get_filename(GTK_FILE_CHOOSER(dialog));
    std::string export_filename = filename;

    // Determine format from file extension or filter
    bool is_svg = false;
    if (export_filename.find(".svg") != std::string::npos)
    {
      is_svg = true;
    }
    else if (export_filename.find(".png") == std::string::npos)
    {
      // No extension found, check active filter
      GtkFileFilter* active_filter = gtk_file_chooser_get_filter(GTK_FILE_CHOOSER(dialog));
      if (active_filter == svg_filter)
      {
        export_filename += ".svg";
        is_svg = true;
      }
      else
      {
        export_filename += ".png";
        is_svg = false;
      }
    }

    try
    {
      // Get the drawing area allocation
      GtkAllocation allocation;
      gtk_widget_get_allocation(m_drawing_area, &allocation);

      cairo_surface_t* surface;
      cairo_t* cr;

      if (is_svg)
      {
        // Create SVG surface
        surface = cairo_svg_surface_create(export_filename.c_str(), allocation.width, allocation.height);
        cr = cairo_create(surface);

        // Draw the topology
        drawTopology(cr);

        // SVG surface saves automatically when destroyed
        addLogMessage("Topology exported to SVG: " + export_filename);
      }
      else
      {
        // Create PNG surface
        surface = cairo_image_surface_create(CAIRO_FORMAT_ARGB32, allocation.width, allocation.height);
        cr = cairo_create(surface);

        // Draw the topology
        drawTopology(cr);

        // Save to PNG file
        cairo_surface_write_to_png(surface, export_filename.c_str());
        addLogMessage("Topology exported to PNG: " + export_filename);
      }

      // Cleanup
      cairo_destroy(cr);
      cairo_surface_destroy(surface);
    }
    catch (const std::exception& e)
    {
      addLogMessage("Export failed: " + std::string(e.what()));
    }

    g_free(filename);
  }

  gtk_widget_destroy(dialog);
}

TopologyGraph NetworkTopologyWindow::createGraphFromTopology() const
{
  TopologyGraph graph;
  std::set<std::pair<std::string, std::string>> processed_edges;

  const auto& topology = m_topology_crawler->get_topology();

  // Create nodes
  for (const auto& [ip, device_info] : topology)
  {
    TopologyNode node;
    node.ip = ip;
    node.device_name = device_info.device_name;

    // Treat all nodes as I/O Devices with consistent styling
    node.device_type = "device";

    // Set system description from device info (LLDP Local System Description)
    node.sys_desc = device_info.sys_desc;

    // Collect all unique local ports
    std::map<int, PortInfo> unique_ports;
    for (const auto& neighbor : device_info.neighbors)
    {
      if (!neighbor.local_port.port_id.empty())
        unique_ports[neighbor.local_port.port_num] = neighbor.local_port;
    }
    for (const auto& [port_num, port_info] : unique_ports)
    {
      node.ports.push_back(port_info);
    }

    graph.nodes[ip] = node;
  }

  // Create edges (avoid duplicates)
  for (const auto& [ip, device_info] : topology)
  {
    for (const auto& neighbor : device_info.neighbors)
    {
      // Find the target IP from management addresses
      for (const auto& mgmt_addr : neighbor.mgmt_addrs)
      {
        // Create edge key to avoid duplicates
        std::pair<std::string, std::string> edge_key =
            (ip < mgmt_addr) ? std::make_pair(ip, mgmt_addr) : std::make_pair(mgmt_addr, ip);

        if (processed_edges.find(edge_key) == processed_edges.end())
        {
          TopologyEdge edge;
          edge.from_ip = ip;
          edge.to_ip = mgmt_addr;
          edge.from_port = neighbor.local_port;
          edge.to_port = neighbor.remote_port;
          edge.mgmt_addrs = neighbor.mgmt_addrs;
          edge.connection_type = "ethernet";

          graph.edges.push_back(edge);
          processed_edges.insert(edge_key);
        }
      }
    }
  }

  return graph;
}

void NetworkTopologyWindow::applySpringLayout(TopologyGraph& graph, int iterations)
{
  if (graph.nodes.empty())
    return;

  // Mark layout as starting
  m_layout_running = true;
  m_current_iteration = 0;
  m_current_mean_speed = 0.0;

  // Update button label to show "Stop Layout"
  g_idle_add(
      [](gpointer user_data) -> gboolean
      {
        NetworkTopologyWindow* window = static_cast<NetworkTopologyWindow*>(user_data);
        window->updateLayoutButtonLabel();
        return G_SOURCE_REMOVE;
      },
      this);

  // Physics simulation parameters
  const double dt = 0.016;            // Time step for integration (16ms)
  const double k = 0.8;               // Spring force constant
  const double repulsion = 2400000.0; // Node repulsion force constant
  const double damping = 2.20;        // Velocity damping coefficient
  const double max_speed = 12000.0;   // Maximum node velocity limit

  // Node physics state
  std::map<std::string, std::pair<double, double>> vel; // velocities
  std::map<std::string, std::pair<double, double>> acc; // accelerations

  // Initialize physics state
  for (const auto& [ip, node] : graph.nodes)
  {
    vel[ip] = {0.0, 0.0};
    acc[ip] = {0.0, 0.0};
  }

  // Initialize positions randomly if needed
  std::random_device rd;
  std::mt19937 gen(rd());
  std::uniform_real_distribution<> pos_dist(-300.0, 300.0);

  for (auto& [ip, node] : graph.nodes)
  {
    if (node.x == 0.0 && node.y == 0.0)
    {
      node.x = pos_dist(gen);
      node.y = pos_dist(gen);
    }
  }

  // Main physics simulation loop
  for (int iter = 0; iter < iterations && !m_layout_stop_requested; ++iter)
  {
    m_current_iteration = iter;

    // Clear accelerations
    for (auto& [ip, a] : acc)
    {
      a = {0.0, 0.0};
    }

    // Apply spring forces between connected nodes
    for (const auto& edge : graph.edges)
    {
      auto node_a = graph.nodes.find(edge.from_ip);
      auto node_b = graph.nodes.find(edge.to_ip);

      if (node_a == graph.nodes.end() || node_b == graph.nodes.end())
        continue;

      // Calculate spring force between connected nodes
      double dx = node_b->second.x - node_a->second.x;
      double dy = node_b->second.y - node_a->second.y;
      double len = std::sqrt(dx * dx + dy * dy);

      if (len > 1e-9)
      {
        double dir_x = dx / len;
        double dir_y = dy / len;

        // Spring force calculation: F = k * (current_length - rest_length) * strength
        // Standard spring parameters for network topology visualization
        double rest_length = 70.0;
        double strength = 1.0;
        double force = k * (len - rest_length) * strength;

        double fx = dir_x * force;
        double fy = dir_y * force;

        // Apply equal and opposite forces
        acc[edge.from_ip].first += fx;
        acc[edge.from_ip].second += fy;
        acc[edge.to_ip].first -= fx;
        acc[edge.to_ip].second -= fy;
      }
    }

    // Apply repulsion forces between all node pairs
    for (auto it1 = graph.nodes.begin(); it1 != graph.nodes.end(); ++it1)
    {
      for (auto it2 = std::next(it1); it2 != graph.nodes.end(); ++it2)
      {
        double dx = it1->second.x - it2->second.x;
        double dy = it1->second.y - it2->second.y;
        double dist_sq = dx * dx + dy * dy + 1.0; // Add small offset to prevent division by zero
        double dist = std::sqrt(dist_sq);

        if (dist > 1e-9)
        {
          double dir_x = dx / dist;
          double dir_y = dy / dist;

          // Inverse square law repulsion force
          double force = repulsion / dist_sq;
          double fx = dir_x * force;
          double fy = dir_y * force;

          // Apply repulsion forces
          acc[it1->first].first += fx;
          acc[it1->first].second += fy;
          acc[it2->first].first -= fx;
          acc[it2->first].second -= fy;
        }
      }
    }

    // Numerical integration using Velocity Verlet method
    double total_speed = 0.0;
    int node_count = 0;

    for (auto& [ip, node] : graph.nodes)
    {
      // Update velocity: v = v + a * dt
      vel[ip].first += acc[ip].first * dt;
      vel[ip].second += acc[ip].second * dt;

      // Apply damping: v = v / (1 + damping * dt)
      double damp_factor = 1.0 / (1.0 + damping * dt);
      vel[ip].first *= damp_factor;
      vel[ip].second *= damp_factor;

      // Limit maximum speed
      double speed = std::sqrt(vel[ip].first * vel[ip].first + vel[ip].second * vel[ip].second);
      if (speed > max_speed)
      {
        vel[ip].first = (vel[ip].first / speed) * max_speed;
        vel[ip].second = (vel[ip].second / speed) * max_speed;
        speed = max_speed;
      }

      // Update position: x = x + v * dt
      node.x += vel[ip].first * dt;
      node.y += vel[ip].second * dt;

      total_speed += speed;
      node_count++;
    }

    // Calculate mean speed for convergence
    m_current_mean_speed = (node_count > 0) ? (total_speed / node_count) : 0.0;

    // Check for convergence (low mean speed indicates equilibrium)
    if (m_current_mean_speed < 0.5)
    {
      break; // Physics has reached equilibrium
    }

    // Update display every 10 iterations for smooth animation
    if (iter % 10 == 0)
    {
      g_idle_add(
          [](gpointer user_data) -> gboolean
          {
            auto* data = static_cast<std::pair<NetworkTopologyWindow*, TopologyGraph*>*>(user_data);
            NetworkTopologyWindow* win = data->first;
            TopologyGraph* graph = data->second;

            win->m_current_graph = *graph;
            gtk_widget_queue_draw(win->m_drawing_area);

            delete graph;
            delete data;
            return G_SOURCE_REMOVE;
          },
          new std::pair<NetworkTopologyWindow*, TopologyGraph*>(this, new TopologyGraph(graph)));

      // Small delay for animation
      std::this_thread::sleep_for(std::chrono::milliseconds(16));
    }
  }

  // Mark layout as finished
  m_layout_running = false;

  // Update button label back to "Apply Layout"
  g_idle_add(
      [](gpointer user_data) -> gboolean
      {
        NetworkTopologyWindow* window = static_cast<NetworkTopologyWindow*>(user_data);
        window->updateLayoutButtonLabel();
        return G_SOURCE_REMOVE;
      },
      this);

  // Final redraw to show completed layout
  if (m_drawing_area && GTK_IS_WIDGET(m_drawing_area))
    gtk_widget_queue_draw(m_drawing_area);
}

void NetworkTopologyWindow::updateLayoutButtonLabel()
{
  if (!m_layout_button || !GTK_IS_TOOL_ITEM(m_layout_button))
    return;

  if (m_layout_running)
  {
    gtk_tool_button_set_label(GTK_TOOL_BUTTON(m_layout_button), "Stop Layout");
    gtk_tool_item_set_tooltip_text(m_layout_button, "Stop the running spring layout algorithm");
  }
  else
  {
    gtk_tool_button_set_label(GTK_TOOL_BUTTON(m_layout_button), "Apply Layout");
    gtk_tool_item_set_tooltip_text(m_layout_button, "Start spring layout algorithm to reorganize nodes");
  }
}


// Utility functions
size_t NetworkTopologyWindow::findNodeUnderMouse(double x, double y) const
{
  // Transform mouse coordinates to world coordinates
  double world_x = (x - m_pan_x) / m_zoom_factor;
  double world_y = (y - m_pan_y) / m_zoom_factor;

  // Check each node
  size_t index = 0;
  for (const auto& [ip, node] : m_current_graph.nodes)
  {
    double node_width = 120.0;
    double node_height = 80.0;

    if (world_x >= node.x - node_width / 2 && world_x <= node.x + node_width / 2 &&
        world_y >= node.y - node_height / 2 && world_y <= node.y + node_height / 2)
    {
      return index;
    }
    index++;
  }

  return SIZE_MAX;
}

void NetworkTopologyWindow::zoomAt(double zoom_delta, double center_x, double center_y)
{
  double old_zoom = m_zoom_factor;
  m_zoom_factor *= zoom_delta;

  // Clamp zoom factor
  if (m_zoom_factor < 0.1)
    m_zoom_factor = 0.1;
  if (m_zoom_factor > 5.0)
    m_zoom_factor = 5.0;

  // Adjust pan to zoom at center point
  double zoom_change = m_zoom_factor / old_zoom;
  m_pan_x = center_x - (center_x - m_pan_x) * zoom_change;
  m_pan_y = center_y - (center_y - m_pan_y) * zoom_change;
}

void NetworkTopologyWindow::resetView()
{
  // If no nodes, just reset to origin
  if (m_current_graph.nodes.empty())
  {
    m_zoom_factor = 1.0;
    m_pan_x = 0.0;
    m_pan_y = 0.0;
    gtk_widget_queue_draw(m_drawing_area);
    return;
  }

  // Get current widget size for viewport
  GtkAllocation allocation;
  gtk_widget_get_allocation(m_drawing_area, &allocation);
  double viewport_width = allocation.width;
  double viewport_height = allocation.height;
  
  // Account for widget position offset in viewport height calculation
  if (allocation.y < 0) {
    viewport_height = std::max(100.0, viewport_height + allocation.y);
  }

  // Calculate bounding box of all nodes
  double min_x = std::numeric_limits<double>::max();
  double max_x = std::numeric_limits<double>::lowest();
  double min_y = std::numeric_limits<double>::max();
  double max_y = std::numeric_limits<double>::lowest();

  for (const auto& [ip, node] : m_current_graph.nodes)
  {
    double node_margin = 60.0; // Half node width for padding
    min_x = std::min(min_x, node.x - node_margin);
    max_x = std::max(max_x, node.x + node_margin);
    min_y = std::min(min_y, node.y - node_margin);
    max_y = std::max(max_y, node.y + node_margin);
  }

  // Calculate center of all nodes
  double nodes_center_x = (min_x + max_x) / 2.0;
  double nodes_center_y = (min_y + max_y) / 2.0;

  // Calculate bounding box dimensions
  double nodes_width = max_x - min_x;
  double nodes_height = max_y - min_y;
  
  // Ensure we have reasonable node dimensions
  if (nodes_width <= 0) nodes_width = 120.0; // Default node width
  if (nodes_height <= 0) nodes_height = 120.0; // Default node height

  // Calculate zoom to fit all nodes with some padding
  double zoom_x = viewport_width / (nodes_width * 1.2);   // 20% padding
  double zoom_y = viewport_height / (nodes_height * 1.2); // 20% padding
  double fit_zoom = std::min(zoom_x, zoom_y);

  // Clamp zoom to reasonable range
  m_zoom_factor = std::max(0.1, std::min(3.0, fit_zoom));

  // Calculate the effective visible area center
  double effective_center_x = viewport_width / 2.0;
  double effective_center_y = viewport_height / 2.0;
  
  // Adjust for toolbar offset - shift the effective center down by full offset
  if (allocation.y < 0) {
    effective_center_y += (-allocation.y);
  }
  
  // Center the view on the nodes within the effective visible area
  m_pan_x = effective_center_x - (nodes_center_x * m_zoom_factor);
  m_pan_y = effective_center_y - (nodes_center_y * m_zoom_factor);
  
  // Force a redraw
  gtk_widget_queue_draw(m_drawing_area);
}


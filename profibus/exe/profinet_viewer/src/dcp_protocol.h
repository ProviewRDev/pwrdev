/**
 * DCP Frame - handles serialization/deserialization of PROFINET DCP frames
 */
class DCPFrame
{
public:
  enum class FrameType : uint8_t
  {
    Request = 0x00,
    Response = 0x01
  };

  enum class ServiceType : uint8_t
  {
    Identify = 0x05,
    Get = 0x03,
    Set = 0x04
  };

  DCPFrame();

  void setDestination(const MacAddress& mac);
  void setSource(const MacAddress& mac);
  void setFrameType(FrameType type);
  void setServiceType(ServiceType service);
  void setTransactionId(uint32_t id);

  void addIPOption(const IPAddress& ip, const IPAddress& subnet, const IPAddress& gateway);
  void addNameOption(const std::string& name);
  void addAllOption();
  void addBlinkLEDOption();
  void addEndTransactionOption();
  void
  addResetToFactoryOption(const std::array<uint8_t, 2>& reset_mode = ResetFactoryModes::RESET_COMMUNICATION);

  std::vector<uint8_t> serialize() const;
  bool deserialize(const std::vector<uint8_t>& data);

  uint32_t getTransactionId() const { return m_transaction_id; }
  MacAddress getSourceMAC() const;
  FrameType getFrameType() const { return m_frame_type; }
  ServiceType getServiceType() const { return m_service_type; }
  FrameID getDetectedFrameId() const { return m_detected_frame_id; }
  const std::vector<std::unique_ptr<DCPDataBlock>>& getParsedBlocks() const { return m_parsed_blocks; }

  // Convenience methods to get specific block types
  std::vector<const ControlResponseBlock*> getControlBlocks() const;

  // Check for control block errors
  bool hasControlBlockErrors() const;
  std::vector<std::string> getControlBlockErrors() const;

private:
  MacAddress m_dest_mac, m_src_mac;
  FrameType m_frame_type;
  ServiceType m_service_type;
  uint32_t m_transaction_id;
  FrameID m_detected_frame_id;
  std::vector<uint8_t> m_block_data;
  std::vector<std::unique_ptr<DCPDataBlock>> m_parsed_blocks;

  void addDCPBlock(uint8_t option, uint8_t suboption, const std::vector<uint8_t>& data);
  bool parseDCPBlocksToObjects(const uint8_t* data, size_t length);
};


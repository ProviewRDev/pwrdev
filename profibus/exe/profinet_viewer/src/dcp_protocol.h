// Basic protocol types
struct MacAddress
{
  std::array<uint8_t, 6> addr;

  MacAddress() : addr{0} {}
  explicit MacAddress(const std::array<uint8_t, 6>& a) : addr(a) {}
  MacAddress(uint8_t a, uint8_t b, uint8_t c, uint8_t d, uint8_t e, uint8_t f) : addr{a, b, c, d, e, f} {}

  std::string toString() const;
  bool fromString(const std::string& str);
  bool operator==(const MacAddress& other) const { return addr == other.addr; }
  bool operator<(const MacAddress& other) const { return addr < other.addr; }
};

struct IPAddress
{
  uint32_t addr;

  IPAddress() : addr(0) {}
  explicit IPAddress(uint32_t a) : addr(a) {}
  IPAddress(uint8_t a, uint8_t b, uint8_t c, uint8_t d) : addr((a << 24) | (b << 16) | (c << 8) | d) {}

  std::string toString() const;
  bool fromString(const std::string& str);
  bool operator==(const IPAddress& other) const { return addr == other.addr; }

  bool isValid() const { return addr != 0; }
};


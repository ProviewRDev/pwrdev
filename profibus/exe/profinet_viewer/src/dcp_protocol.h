/**
 * Abstract base class for DCP data blocks
 */
class DCPDataBlock
{
public:
  DCPDataBlock(uint8_t option, uint8_t suboption) : option_(option), suboption_(suboption) {}

  virtual ~DCPDataBlock() = default;

  uint8_t getOption() const { return option_; }
  uint8_t getSuboption() const { return suboption_; }

  virtual std::vector<uint8_t> serialize() const = 0;

protected:
  uint8_t option_;
  uint8_t suboption_;
};


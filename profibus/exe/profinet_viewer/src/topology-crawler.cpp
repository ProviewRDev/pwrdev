static std::string val_to_str(const netsnmp_variable_list* var)
{
  char buf[1024];
  snprint_value(buf, sizeof(buf), var->name, var->name_length, var);
  return std::string(buf);
}

// Convert raw octet address stored as OID suffix into IP string (IPv4 and IPv6)
static std::optional<std::string> decode_addr_from_oid_suffix(const oid* arr, size_t arr_len, size_t start)
{
  // LLDP management address format in OID:
  // ...<ifSubtype>.<addrLen>.<addr_byte1>.<addr_byte2>...
  // For IPv4: ifSubtype=1, addrLen=4, followed by 4 address bytes
  // For IPv6: ifSubtype=2, addrLen=16, followed by 16 address bytes

  if (start + 2 >= arr_len)
    return std::nullopt;

  size_t pos = start;

  // Look for IPv4 pattern: ifSubtype + addrLen + addr_bytes
  // ifSubtype can be 1 (IPv4) or 3 (IPv4 address) depending on device implementation
  if (pos + 2 <= arr_len && (arr[pos] == 1 || arr[pos] == 3))
  {
    size_t addr_len = arr[pos + 1];

    // Standard IPv4: length=4
    if (addr_len == 4 && pos + 6 <= arr_len)
    {
      std::ostringstream s;
      s << (int)arr[pos + 2] << "." << (int)arr[pos + 3] << "." << (int)arr[pos + 4] << "."
        << (int)arr[pos + 5];
      return s.str();
    }

    // Some devices encode IPv4 differently (e.g., length=10 for "10.254.3.114")
    // Try to find 4 consecutive values that form a valid IPv4 address
    if (addr_len > 4 && pos + 2 + addr_len <= arr_len)
    {
      for (size_t i = 0; i <= addr_len - 4; ++i)
      {
        // Check if 4 consecutive bytes form a reasonable IPv4 address
        if (arr[pos + 2 + i] > 0 && arr[pos + 2 + i] <= 255 && arr[pos + 3 + i] <= 255 &&
            arr[pos + 4 + i] <= 255 && arr[pos + 5 + i] <= 255)
        {
          std::ostringstream s;
          s << (int)arr[pos + 2 + i] << "." << (int)arr[pos + 3 + i] << "." << (int)arr[pos + 4 + i] << "."
            << (int)arr[pos + 5 + i];
          return s.str();
        }
      }
    }
  }

  // Look for pattern: ifSubtype(2) + addrLen(16) + 16 bytes for IPv6
  if (pos + 18 <= arr_len && arr[pos] == 2 && arr[pos + 1] == 16)
  {
    std::ostringstream s;
    s << std::hex;
    for (size_t i = 0; i < 16; i += 2)
    {
      if (i > 0)
        s << ":";
      unsigned int val = (arr[pos + 2 + i] << 8) | arr[pos + 2 + i + 1];
      s << val;
    }
    return s.str();
  }

  // Fallback: try to find any 4-byte sequence that looks like an IPv4 address
  // Prefer sequences that start with common private network ranges (10.x, 172.x, 192.x)
  std::string best_ip;
  int best_score = -1;

  for (size_t p = start; p + 4 <= arr_len; ++p)
  {
    bool valid_ipv4 = true;
    for (size_t j = 0; j < 4; ++j)
    {
      if (arr[p + j] > 255)
      {
        valid_ipv4 = false;
        break;
      }
    }
    if (valid_ipv4)
    {
      // Additional check: make sure it's not all zeros or looks reasonable
      if (arr[p] > 0 && (arr[p] != arr[p + 1] || arr[p + 1] != arr[p + 2] || arr[p + 2] != arr[p + 3]))
      {
        std::ostringstream s;
        s << (int)arr[p] << "." << (int)arr[p + 1] << "." << (int)arr[p + 2] << "." << (int)arr[p + 3];
        std::string candidate = s.str();

        // Score based on how likely this is a real IP address
        int score = 0;
        if (arr[p] == 10)
          score += 3; // 10.x.x.x networks
        else if (arr[p] == 172)
          score += 2; // 172.x.x.x networks
        else if (arr[p] == 192)
          score += 2; // 192.x.x.x networks
        else if (arr[p] >= 1 && arr[p] <= 223)
          score += 1; // Valid unicast range

        // Prefer addresses where bytes look reasonable (not too small)
        if (arr[p + 1] > 0)
          score++;
        if (arr[p + 2] > 0)
          score++;
        if (arr[p + 3] > 0)
          score++;

        if (score > best_score)
        {
          best_score = score;
          best_ip = candidate;
        }
      }
    }
  }

  if (!best_ip.empty())
  {
    return best_ip;
  }

  return std::nullopt;
}

// Walk a base OID and return the variable list (collected)
std::vector<netsnmp_variable_list*> snmp_walk_vars(netsnmp_session* ss, const char* base_oid_str)
{
  oid base_oid[MAX_OID_LEN];
  size_t base_len = MAX_OID_LEN;
  if (!read_objid(base_oid_str, base_oid, &base_len))
  {
    // Note: This is a static function, can't use log_message here
    // Error will be handled by caller
    return {};
  }

  oid cur[MAX_OID_LEN];
  size_t cur_len = base_len;
  memcpy(cur, base_oid, base_len * sizeof(oid));

  std::vector<netsnmp_variable_list*> collected;

  while (true)
  {
    netsnmp_pdu* pdu = snmp_pdu_create(SNMP_MSG_GETNEXT);
    snmp_add_null_var(pdu, cur, cur_len);
    netsnmp_pdu* response = nullptr;
    int status = snmp_synch_response(ss, pdu, &response);
    if (status != STAT_SUCCESS || !response)
    {
      if (response)
        snmp_free_pdu(response);
      break;
    }
    if (response->errstat != SNMP_ERR_NOERROR)
    {
      snmp_free_pdu(response);
      break;
    }
    if (!response->variables)
    {
      snmp_free_pdu(response);
      break;
    }

    // If next OID is not under the base subtree -> stop
    if (snmp_oid_compare(base_oid, base_len, response->variables->name, base_len) != 0)
    {
      // not in subtree (comparison uses first base_len elements)
      snmp_free_pdu(response);
      break;
    }

    // Copy the varbind (we must duplicate because response freed later)
    netsnmp_variable_list* v = snmp_clone_varbind(response->variables);
    if (v)
      collected.push_back(v);

    // Set cur to returned OID
    memcpy(cur, response->variables->name, response->variables->name_length * sizeof(oid));
    cur_len = response->variables->name_length;

    snmp_free_pdu(response);
  }

  return collected;
}

// Parse LLDP data from varbinds into map keyed by (timeMark, localPortNum,
// remIndex)
std::map<Key, Neighbor> parse_lldp_vars(const std::vector<netsnmp_variable_list*>& vars)
{
  std::map<Key, Neighbor> m;

  // base for lldpRemEntry fields: .1.0.8802.1.1.2.1.4.1.1  (field id follows)
  // We'll detect fields by checking the field id present right after the base.
  // But instead of hard-coding base length, compute from a sample OID prefix
  // where available. We'll just inspect each var's name[] array directly.

  for (const auto* v : vars)
  {
    const oid* arr = v->name;
    size_t alen = v->name_length;

    // we need at least field id + 3 indexes => field + timeMark + local + rem
    if (alen < 4)
      continue;

    // Find the position of the LLDP '...1.4.1.1' pattern inside OID.
    // Simpler approach: walk from the end to extract last 3 index ints
    // (timeMark, localPortNum, remIndex). LLDP's lldpRemEntry indexes are the
    // LAST three components of the OID for lldpRemEntry.* fields. So remIndex =
    // arr[alen-1], localPortNum = arr[alen-2], timeMark = arr[alen-3]
    int remIndex = (int)arr[alen - 1];
    int localPortNum = (int)arr[alen - 2];
    int timeMark = (int)arr[alen - 3];

    Key k = std::make_tuple(timeMark, localPortNum, remIndex);
    Neighbor& n = m[k]; // creates default if missing
    n.timeMark = timeMark;
    n.localPortNum = localPortNum;
    n.remIndex = remIndex;

    // identify the field id (the component BEFORE the three indexes)
    int fieldId = (int)arr[alen - 4];

    // field mapping (from LLDP-MIB lldpRemEntry definitions)
    // 4 = lldpRemLocalPortNum (local port number field)
    // More importantly known fields:
    // 5 = lldpRemChassisId
    // 6 = lldpRemChassisIdSubtype
    // 7 = lldpRemPortId
    // 8 = lldpRemPortDesc
    // 9 = lldpRemSysName
    // 10 = lldpRemSysDesc
    // 11 = lldpRemSysCapSupported
    // 12 = lldpRemSysCapEnabled

    switch (fieldId)
    {
    case 5:
    {
      // chassis id may be Hex-STRING (MAC) or printable
      if (v->type == ASN_OCTET_STR)
      {
        unsigned char* bytes = static_cast<unsigned char*>(v->val.string);
        size_t len = v->val_len;
        // print as hex MAC if length is 6
        if (len == 6)
        {
          std::ostringstream oss;
          for (size_t i = 0; i < len; ++i)
          {
            if (i)
              oss << ":";
            oss << std::hex << std::setw(2) << std::setfill('0') << (int)bytes[i];
          }
          n.chassis_id = oss.str();
        }
        else
        {
          // fallback: printable string
          n.chassis_id = std::string(reinterpret_cast<char*>(bytes), len);
        }
      }
      else
      {
        n.chassis_id = val_to_str(v);
      }
    }
    break;
    case 7:
    {
      n.port_id = val_to_str(v);
    }
    break;
    case 8:
    {
      n.port_desc = val_to_str(v);
    }
    break;
    case 9:
    {
      n.sys_name = val_to_str(v);
    }
    break;
    case 10:
    {
      n.sys_desc = val_to_str(v);
    }
    break;
    default:
      // ignore other fields here
      break;
    }
  }

  return m;
}

// Debug function to print OID for troubleshooting
// Parse lldpRemManAddrTable varbinds and attach mgmt addrs to corresponding
// neighbors. The lldpRemManAddrTable entries have indexes that include the
// management address bytes — tricky to parse, but the last three indexes are
// still (timeMark, localPortNum, remIndex) somewhere near the front. We'll
// attempt to find the corresponding (timeMark, localPortNum, remIndex) by
// searching the varbind OID.
void attach_manaddrs(std::map<Key, Neighbor>& m, const std::vector<netsnmp_variable_list*>& vars)
{
  for (const auto* v : vars)
  {
    const oid* arr = v->name;
    size_t alen = v->name_length;
    if (alen < 6)
      continue;

    // Uncomment for debugging: debug_oid(arr, alen, "ManAddr ");

    // LLDP Management Address table OID structure:
    // .1.0.8802.1.1.2.1.4.2.1.<field>.<timeMark>.<localPort>.<remIndex>.<ifSubtype>.<addrLen>.<addr_bytes>
    // We need to find the field position first, then extract the indexes

    // Look for the lldpRemManAddrTable base (.1.0.8802.1.1.2.1.4.2.1)
    // and then extract field + 3 indexes + address info

    // Try different positions to find timeMark, localPort, remIndex pattern
    for (size_t p = 0; p + 6 <= alen; ++p) // need at least field + 3 indexes + ifSubtype + addrLen
    {
      // Skip field value - not used in this function
      int tm = arr[p + 1];
      int lp = arr[p + 2];
      int ri = arr[p + 3];

      Key k = std::make_tuple(tm, lp, ri);
      if (m.find(k) != m.end())
      {
        // Found matching neighbor, try to decode address starting after the 3 indexes
        auto opt = decode_addr_from_oid_suffix(arr, alen, p + 4);
        if (opt)
        {
          // Skip IPv6 addresses (contain colons)
          bool is_ipv6 = (opt->find(':') != std::string::npos);
          if (!is_ipv6)
          {
            // Check if this address is already in the list to avoid duplicates
            bool already_exists = std::any_of(m[k].mgmt_addrs.begin(), m[k].mgmt_addrs.end(),
                                              [&opt](const auto& existing) { return existing == *opt; });
            if (!already_exists)
            {
              m[k].mgmt_addrs.push_back(*opt);
            }
          }
          break;
        }
      }
    }

    // Uncomment for debugging:
    // if (!matched)
    // {
    //   std::cout << "  -> Failed to match management address OID" <<
    //   std::endl;
    // }
  }
}

LldpSnmpClient::LldpSnmpClient(std::string community) : community_(std::move(community))
{
  init_snmp("lldp_crawler");
  SOCK_STARTUP;
}

LldpSnmpClient::~LldpSnmpClient() { SOCK_CLEANUP; }

void LldpSnmpClient::set_log_callback(LogCallback callback) { log_callback_ = callback; }

void LldpSnmpClient::log_message(const std::string& message)
{
  if (log_callback_)
  {
    log_callback_(message);
  }
  else
  {
    // Fallback to stderr for SNMP client errors
    std::cerr << message << std::endl;
  }
}

std::string LldpSnmpClient::get_device_name(const std::string& ip)
{
  snmp_session session{};
  snmp_sess_init(&session);
  session.peername = strdup(ip.c_str());
  session.version = SNMP_VERSION_1; // Many Profinet devices use SNMPv1
  session.community = reinterpret_cast<u_char*>(const_cast<char*>(community_.c_str()));
  session.community_len = community_.size();
  session.timeout = 300000; // 0.3 seconds (was 1 second)
  session.retries = 0;      // No retries for faster crawling (was 1)

  netsnmp_session* ss = snmp_open(&session);
  if (!ss)
  {
    // Try SNMPv2c as fallback
    session.version = SNMP_VERSION_2c;
    ss = snmp_open(&session);
    if (!ss)
      return "";
  }

  std::string device_name;

  // 1. First try LLDP Local System Name (.1.0.8802.1.1.2.1.3.3.0)
  oid lldp_sysname_oid[] = {1, 0, 8802, 1, 1, 2, 1, 3, 3, 0};
  size_t lldp_sysname_oid_len = sizeof(lldp_sysname_oid) / sizeof(oid);

  netsnmp_pdu* pdu = snmp_pdu_create(SNMP_MSG_GET);
  snmp_add_null_var(pdu, lldp_sysname_oid, lldp_sysname_oid_len);

  netsnmp_pdu* response = nullptr;
  int status = snmp_synch_response(ss, pdu, &response);

  if (status == STAT_SUCCESS && response && response->errstat == SNMP_ERR_NOERROR)
  {
    if (response->variables && response->variables->type == ASN_OCTET_STR)
    {
      device_name =
          std::string(reinterpret_cast<char*>(response->variables->val.string), response->variables->val_len);
    }
  }

  if (response)
    snmp_free_pdu(response);

  // 2. If empty, try standard sysName (.1.3.6.1.2.1.1.5.0)
  if (device_name.empty())
  {
    oid sysname_oid[] = {1, 3, 6, 1, 2, 1, 1, 5, 0};
    size_t sysname_oid_len = sizeof(sysname_oid) / sizeof(oid);

    pdu = snmp_pdu_create(SNMP_MSG_GET);
    snmp_add_null_var(pdu, sysname_oid, sysname_oid_len);

    status = snmp_synch_response(ss, pdu, &response);
    if (status == STAT_SUCCESS && response && response->errstat == SNMP_ERR_NOERROR)
    {
      if (response->variables && response->variables->type == ASN_OCTET_STR)
      {
        device_name = std::string(reinterpret_cast<char*>(response->variables->val.string),
                                  response->variables->val_len);
      }
    }

    if (response)
      snmp_free_pdu(response);
  }

  // 3. Fallback to LLDP Local Chassis ID (.1.0.8802.1.1.2.1.3.2.0)
  if (device_name.empty())
  {
    oid lldp_chassis_oid[] = {1, 0, 8802, 1, 1, 2, 1, 3, 2, 0};
    size_t lldp_chassis_oid_len = sizeof(lldp_chassis_oid) / sizeof(oid);

    pdu = snmp_pdu_create(SNMP_MSG_GET);
    snmp_add_null_var(pdu, lldp_chassis_oid, lldp_chassis_oid_len);

    status = snmp_synch_response(ss, pdu, &response);

    if (status == STAT_SUCCESS && response && response->errstat == SNMP_ERR_NOERROR)
    {
      if (response->variables && response->variables->type == ASN_OCTET_STR)
      {
        device_name = std::string(reinterpret_cast<char*>(response->variables->val.string),
                                  response->variables->val_len);
      }
    }

    if (response)
      snmp_free_pdu(response);
  }

  snmp_close(ss);
  return device_name;
}

// Get local system description for a device (LLDP Local System Description)

{
  std::cout << "\n=== TOPOLOGY ===\n";
  for (const auto& [ip, device_info] : topology_)
  {
    std::cout << ip;
    if (!device_info.device_name.empty())
    {
      std::cout << " (" << device_info.device_name << ")";
    }
    std::cout << ":\n";

    for (const auto& n : device_info.neighbors)
    {
      // Display local port information
      std::cout << "  Local Port: ";
      if (!n.local_port.port_id.empty())
      {
        std::cout << n.local_port.port_id;
        if (!n.local_port.port_desc.empty())
          std::cout << " (" << n.local_port.port_desc << ")";
      }
      else
      {
        std::cout << "port-" << n.localPortNum;
      }

      // Display connection arrow and remote device
      std::cout << " -> ";

      // Display remote device name or chassis ID
      std::string remote_device = n.sys_name.empty() ? n.chassis_id : n.sys_name;
      std::cout << remote_device;

      // Display remote port information
      std::cout << " [Remote Port: ";
      if (!n.remote_port.port_id.empty())
      {
        std::cout << n.remote_port.port_id;
        if (!n.remote_port.port_desc.empty())
          std::cout << " - " << n.remote_port.port_desc;
      }
      else
      {
        std::cout << n.port_id;
      }
      std::cout << "]";

      // Display management addresses
      if (!n.mgmt_addrs.empty())
      {
        std::cout << " (Mgmt: ";
        bool first = true;
        for (const auto& a : n.mgmt_addrs)
        {
          if (!first)
            std::cout << ", ";
          std::cout << a;
          first = false;
        }
        std::cout << ")";
      }
      std::cout << "\n";
    }
  }
}


// Print summary statistics
void TopologyCrawler::print_summary() const
{
  std::cout << "\n=== TOPOLOGY SUMMARY ===\n";
  std::cout << "Total devices discovered: " << topology_.size() << "\n";

  size_t total_connections = 0;
  for (const auto& [ip, device_info] : topology_)
  {
    total_connections += device_info.neighbors.size();
  }
  std::cout << "Total LLDP connections: " << total_connections << "\n";

  std::cout << "Devices with LLDP neighbors:\n";
  for (const auto& [ip, device_info] : topology_)
  {
    if (!device_info.neighbors.empty())
    {
      std::cout << "  " << ip;
      if (!device_info.device_name.empty())
      {
        std::cout << " (" << device_info.device_name << ")";
      }
      std::cout << ": " << device_info.neighbors.size() << " neighbors\n";
    }
  }
}

// Helper function to add device to topology with deduplication
void TopologyCrawler::add_device_to_topology(const std::string& ip, const std::string& device_name,
                                             const std::string& sys_desc, const std::vector<Neighbor>& neighs)
{
  // Create DeviceInfo with all required fields
  TopologyDeviceInfo device_info;
  device_info.device_name = device_name;
  device_info.sys_desc = sys_desc;
  device_info.neighbors = neighs;
  device_info.ip_address = ip; // Store the IP address that was used to discover this device

  // Use device name as key for deduplication (fall back to IP if no device name)
  std::string device_key = device_name.empty() ? ip : device_name;

  // Check if we already have this device under a different IP
  auto existing_device = std::find_if(topology_.begin(), topology_.end(),
                                      [&device_key, &ip](const auto& pair)
                                      {
                                        const std::string& existing_key = pair.second.device_name.empty()
                                                                              ? pair.first
                                                                              : pair.second.device_name;
                                        return existing_key == device_key && pair.first != ip;
                                      });

  if (existing_device != topology_.end())
  {
    // Merge neighbors from this IP with existing device entry
    log_message("Merging duplicate device: " + device_name + " (IP: " + ip + " -> " + existing_device->first +
                ")");

    // Add new neighbors to existing device, avoiding duplicates
    for (const auto& new_neighbor : neighs)
    {
      bool duplicate = false;
      for (const auto& existing_neighbor : existing_device->second.neighbors)
      {
        // Consider neighbors the same if they have the same chassis_id or sys_name
        if ((!new_neighbor.chassis_id.empty() && new_neighbor.chassis_id == existing_neighbor.chassis_id) ||
            (!new_neighbor.sys_name.empty() && new_neighbor.sys_name == existing_neighbor.sys_name))
        {
          duplicate = true;
          break;
        }
      }
      if (!duplicate)
      {
        existing_device->second.neighbors.push_back(new_neighbor);
      }
    }

    // Don't add this IP as a separate device
    return;
  }

  topology_[ip] = device_info;
}

// Private method implementation
void TopologyCrawler::crawl(const std::string& ip)
{
  if (visited_.count(ip))
    return;
  visited_.insert(ip);
  log_message("Querying " + ip + " ...");

  auto neighs = client_.fetch_neighbors(ip);
  std::string device_name = client_.get_device_name(ip);

  std::string msg = "Found " + std::to_string(neighs.size()) + " LLDP neighbors";
  if (!device_name.empty())
  {
    msg += ", device name: " + device_name;
  }
  log_message(msg);

  // Fetch system description for tooltip display
  std::string sys_desc = client_.get_system_description(ip);

  // Add device to topology with deduplication
  add_device_to_topology(ip, device_name, sys_desc, neighs);

  for (const auto& n : neighs)
  {
    // prefer mgmt address if available
    if (!n.mgmt_addrs.empty())
    {
      for (const auto& mgmt : n.mgmt_addrs)
      {
        // Skip all IPv6 addresses (contain colons) and already visited
        bool is_ipv6 = (mgmt.find(':') != std::string::npos);
        if (!visited_.count(mgmt) && !is_ipv6)
        {
          crawl(mgmt);
        }
      }
    }
    else if (!n.chassis_id.empty())
    {
      // fallback: try resolving chassis_id as hostname (not guaranteed)
      // We'll attempt a DNS resolution only if it looks like a name (contains
      // dot or letters)
      bool looks_like_name = false;
      for (char c : n.chassis_id)
      {
        if (std::isalpha((unsigned char)c) || c == '.')
        {
          looks_like_name = true;
          break;
        }
      }
      if (looks_like_name)
      {
        // naive gethostbyname
        struct hostent* h = gethostbyname(n.chassis_id.c_str());
        if (h && h->h_addr_list && h->h_addr_list[0])
        {
          char buf[64];
          inet_ntop(h->h_addrtype, h->h_addr_list[0], buf, sizeof(buf));
          std::string resolved(buf);
          if (!visited_.count(resolved))
            crawl(resolved);
        }
      }
    }
  }
}

// Filtered crawl method that respects subnet filtering
void TopologyCrawler::crawl_filtered(const std::string& ip)
{
  if (visited_.count(ip))
    return;
  visited_.insert(ip);
  log_message("Querying " + ip + " ...");

  auto neighs = client_.fetch_neighbors(ip);
  std::string device_name = client_.get_device_name(ip);

  std::string msg = "Found " + std::to_string(neighs.size()) + " LLDP neighbors";
  if (!device_name.empty())
  {
    msg += ", device name: " + device_name;
  }
  log_message(msg);

  // Fetch system description for tooltip display
  std::string sys_desc = client_.get_system_description(ip);

  // Add device to topology with deduplication
  add_device_to_topology(ip, device_name, sys_desc, neighs);

  for (const auto& n : neighs)
  {
    // prefer mgmt address if available
    if (!n.mgmt_addrs.empty())
    {
      for (const auto& mgmt : n.mgmt_addrs)
      {
        // Skip IPv6 addresses and already visited
        bool is_ipv6 = (mgmt.find(':') != std::string::npos);
        if (!visited_.count(mgmt) && !is_ipv6)
        {
          // Try all management addresses - no subnet filtering
          log_message("Crawling remote management address: " + mgmt);
          crawl_filtered(mgmt);
        }
      }
    }
    else if (!n.chassis_id.empty())
    {
      // DNS resolution fallback (less reliable for subnet filtering)
      bool looks_like_name = false;
      for (char c : n.chassis_id)
      {
        if (std::isalpha((unsigned char)c) || c == '.')
        {
          looks_like_name = true;
          break;
        }
      }
      if (looks_like_name)
      {
        struct hostent* h = gethostbyname(n.chassis_id.c_str());
        if (h && h->h_addr_list && h->h_addr_list[0])
        {
          char buf[64];
          inet_ntop(h->h_addrtype, h->h_addr_list[0], buf, sizeof(buf));
          std::string resolved(buf);
          if (!visited_.count(resolved))
          {
            log_message("Crawling resolved hostname: " + resolved);
            crawl_filtered(resolved);
          }
        }
      }
    }
  }
}

// Check if IP is in any of the allowed PROFINET subnets
bool TopologyCrawler::is_ip_in_allowed_subnets(const std::string& ip) const
{
  if (!subnet_filtering_enabled_ || profinet_devices_.empty())
    return true;

  for (const auto& device : profinet_devices_)
  {
    if (!device.ip_address.empty() && !device.subnet_mask.empty())
    {
      if (is_same_subnet(ip, device.ip_address, device.subnet_mask))
      {
        return true;
      }
    }
  }
  return false;
}

// Check if two IPs are in the same subnet
bool TopologyCrawler::is_same_subnet(const std::string& ip1, const std::string& ip2,
                                     const std::string& subnet_mask) const
{
  struct in_addr addr1, addr2, mask;

  if (inet_aton(ip1.c_str(), &addr1) == 0 || inet_aton(ip2.c_str(), &addr2) == 0 ||
      inet_aton(subnet_mask.c_str(), &mask) == 0)
  {
    return false;
  }

  // Apply subnet mask to both IPs and compare
  return (addr1.s_addr & mask.s_addr) == (addr2.s_addr & mask.s_addr);
}


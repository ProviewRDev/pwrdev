// EndTransactionBlock implementation
std::vector<uint8_t> EndTransactionBlock::serialize() const
{
  std::vector<uint8_t> data;
  data.reserve(2);

  // Add block qualifier for end transaction
  data.insert(data.end(), block_qualifier_.begin(), block_qualifier_.end());

  return data;
}


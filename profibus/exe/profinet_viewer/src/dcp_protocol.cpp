// Response block implementations

bool NameOfStationResponseBlock::parseFromData(const uint8_t* data, uint16_t length)
{
  if (length < 6) // Need at least option+suboption+length+blockerror+blockinfo = 6 bytes
    return false;

  size_t offset = 4; // Skip option+suboption+length which are already parsed

  // BlockInfo
  memcpy(&block_info_, data + offset, sizeof(block_info_));
  block_info_ = ntohl(block_info_);
  offset += sizeof(block_info_);

  // Remaining data contains block qualifier + name
  uint16_t payload_length = length - offset;

  // Extract name (remaining bytes)
  if (payload_length > 0)
  {
    name_.assign(reinterpret_cast<const char*>(data + offset), payload_length);
    // Remove null terminators
    while (!name_.empty() && name_.back() == '\0')
    {
      name_.pop_back();
    }
  }

#ifdef DEBUG
  std::cout << "NameOfStationResponseBlock: BlockError=" << (int)block_error_
            << ", BlockInfo=" << (int)block_info_ << ", Name='" << name_ << "' (length=" << name_.length()
            << ")" << std::endl;
#endif

  return true;
}

bool IPAddressResponseBlock::parseFromData(const uint8_t* data, uint16_t length)
{
  if (length < 18) // Need at least 6 (header) + 2 (qualifier) + 12 (IP data) = 20, but allow 18 for legacy
    return false;

  size_t offset = 4; // Skip option+suboption+length which are already parsed

  // Extract BlockError and BlockInfo
  block_error_ = data[offset++];
  block_info_ = data[offset++];

  // Remaining data contains block qualifier + IP data
  uint16_t payload_length = length - 6;

  if (payload_length >= 14)
  {
    // Standard format with block qualifier
    std::copy(data + offset, data + offset + 2, block_qualifier_.begin());
    offset += 2;

    uint32_t ip_net, subnet_net, gateway_net;
    std::memcpy(&ip_net, data + offset, 4);
    std::memcpy(&subnet_net, data + offset + 4, 4);
    std::memcpy(&gateway_net, data + offset + 8, 4);

    ip_address_ = ntohl(ip_net);
    subnet_mask_ = ntohl(subnet_net);
    default_gateway_ = ntohl(gateway_net);
  }
  else if (payload_length == 12)
  {
    // Legacy format without block qualifier
    block_qualifier_ = {0x00, 0x00};

    uint32_t ip_net, subnet_net, gateway_net;
    std::memcpy(&ip_net, data + offset, 4);
    std::memcpy(&subnet_net, data + offset + 4, 4);
    std::memcpy(&gateway_net, data + offset + 8, 4);

    ip_address_ = ntohl(ip_net);
    subnet_mask_ = ntohl(subnet_net);
    default_gateway_ = ntohl(gateway_net);
  }
  else
  {
    return false;
  }

  return true;
}

// DeviceFamilyResponseBlock implementation
bool DeviceFamilyResponseBlock::parseFromData(const uint8_t* data, uint16_t length)
{
  if (length < 6) // Need at least option+suboption+length+blockerror+blockinfo = 6 bytes
    return false;

  size_t offset = 4; // Skip option+suboption+length which are already parsed

  // Extract BlockError and BlockInfo
  memcpy(&block_info_, data + offset, sizeof(block_info_));
  block_info_ = ntohs(block_info_);
  offset += sizeof(block_info_);

  // Remaining data contains the device family string
  uint16_t payload_length = length - offset;

  if (payload_length > 0)
  {
    device_family_.assign(reinterpret_cast<const char*>(data + offset), payload_length);

    // Remove any null terminators (matching the old parsing behavior)
    while (!device_family_.empty() && device_family_.back() == '\0')
    {
      device_family_.pop_back();
    }

#ifdef DEBUG
    std::cout << "DeviceFamily Block parsed - Family: '" << device_family_ << "'" << std::endl;
#endif
  }

  return true;
}

// DeviceIDResponseBlock implementation
bool DeviceIDResponseBlock::parseFromData(const uint8_t* data, uint16_t length)
{
  if (length < 10) // Need at least option+suboption+length+blockerror+blockinfo+vendorid+deviceid = 10 bytes
    return false;

  size_t offset = 4; // Skip option+suboption+length which are already parsed

  memcpy(&block_info_, data + offset, sizeof(block_info_));
  block_info_ = ntohs(block_info_);
  offset += sizeof(block_info_);

  memcpy(&vendor_id_, data + offset, sizeof(vendor_id_));
  vendor_id_ = ntohs(vendor_id_);
  offset += sizeof(vendor_id_);

  memcpy(&device_id_, data + offset, sizeof(device_id_));
  device_id_ = ntohs(device_id_);

  return true;
}

bool ControlResponseBlock::parseFromData(const uint8_t* data, uint16_t length)
{
  if (length < 6) // Need at least option+suboption+length+blockerror+blockinfo = 6 bytes
    return false;

  size_t offset = 4; // Skip option+suboption+length which are already parsed

  m_block_option = data[offset++];

  m_block_suboption = data[offset++];

  m_block_error = data[offset++];

  return true;
}


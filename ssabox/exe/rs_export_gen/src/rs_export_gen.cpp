static void load_css()
{
  GtkCssProvider* provider = gtk_css_provider_new();
  const gchar* css = get_dark_theme_css();
  GError* error = NULL;
  gtk_css_provider_load_from_data(provider, css, -1, &error);
  if (error)
  {
    g_warning("CSS load error: %s", error->message);
    g_error_free(error);
  }
  else
  {
    gtk_style_context_add_provider_for_screen(gdk_screen_get_default(), GTK_STYLE_PROVIDER(provider),
                                              GTK_STYLE_PROVIDER_PRIORITY_APPLICATION);
  }
}

int main(int argc, char** argv)
{
  gtk_init(&argc, &argv);
  errh_Interactive();

  /* Load dark theme CSS */
  load_css();

  pwr_tStatus sts = gdh_Init("rs_export_gen");
  if (EVEN(sts))
  {
    fprintf(stderr, "gdh_Init failed - is the runtime running?\n");
    return 1;
  }

  AppData app = {};

  /* Initialize all filters to enabled */
  app.filter_di = true;
  app.filter_do = true;
  app.filter_dv = true;
  app.filter_ai = true;
  app.filter_ao = true;
  app.filter_av = true;
  app.filter_ii = true;
  app.filter_io = true;
  app.filter_iv = true;
  app.filter_co = true;
  app.filter_po = true;
  app.filter_other = true;

  /* Load previously selected signals from select.json */
  load_selected_from_json(&app);

  create_window(&app);
  populate_source_tree(&app);
  apply_filter(&app);

  /* If no previous selection was loaded, select all IO signals by default */
  if (app.selected_names.empty())
    on_select_all_signals(NULL, &app);
  else
    rebuild_selected_list(&app);

  gtk_widget_show_all(app.window);
  gtk_main();

  return 0;
}


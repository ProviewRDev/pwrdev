bool PwrLogParser::is_pwrlog_format(const std::string& line)
{
  if (line.length() < 2)
    return false;

  char severity = line[0];
  return (severity == 'S' || severity == 'I' || severity == 'W' || severity == 'E' || severity == 'F') &&
         line[1] == ' ';
}


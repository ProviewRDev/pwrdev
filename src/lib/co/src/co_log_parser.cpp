std::unique_ptr<LogMessage> LogMessage::create_message(const std::string& line)
{
  LogFormat format = LogParser::detect_format(line);

  switch (format)
  {
  case LogFormat::RFC5424:
  {
    auto msg = std::make_unique<RFC5424Message>();
    msg->parse_from_string(line);
    return msg;
  }
  case LogFormat::PWRLOG:
  {
    auto msg = std::make_unique<PwrLogMessage>();
    msg->parse_from_string(line);
    return msg;
  }
  default:
    return nullptr;
  }
}

LogFormat LogParser::detect_format(const std::string& line)
{
  if (line.empty())
    return LogFormat::UNKNOWN;

  // RFC5424 format detection: use the dedicated function
  if (RFC5424Parser::is_rfc5424_format(line))
    return LogFormat::RFC5424;

  // PWR log format detection: severity character followed by space and program name
  if (line.length() > 2 &&
      (line[0] == 'S' || line[0] == 'I' || line[0] == 'W' || line[0] == 'E' || line[0] == 'F') &&
      line[1] == ' ')
  {
    return LogFormat::PWRLOG;
  }

  return LogFormat::UNKNOWN;
}

std::unique_ptr<LogParser> LogParser::create_parser(const std::string& line)
{
  LogFormat format = detect_format(line);

  switch (format)
  {
  case LogFormat::RFC5424:
    return std::make_unique<RFC5424Parser>();
  case LogFormat::PWRLOG:
    return std::make_unique<PwrLogParser>();
  default:
    return nullptr;
  }
}


PwrLogMessage::PwrLogMessage() : severity_char('I'), pid(0), m_valid(false)
{
  time_GetTime(&timestamp);
  hostname = "localhost";
}

bool PwrLogMessage::parse_from_string(const std::string& line)
{
  size_t pos = 0;
  m_valid = false;

  // Parse: "S programName   12345678 25-09-23 14:32:01.00 message"
  if (!parse_severity(line, pos))
    return false;
  if (!parse_program_name(line, pos))
    return false;
  if (!parse_pid(line, pos))
    return false;
  if (!parse_timestamp(line, pos))
    return false;
  if (!parse_message(line, pos))
    return false;

  m_valid = true;
  return true;
}

bool PwrLogMessage::parse_severity(const std::string& line, size_t& pos)
{
  if (pos >= line.length())
    return false;

  severity_char = line[pos];
  if (severity_char != 'S' && severity_char != 'I' && severity_char != 'W' && severity_char != 'E' &&
      severity_char != 'F')
    return false;

  pos++;
  skip_whitespace(line, pos);
  return true;
}

bool PwrLogMessage::parse_program_name(const std::string& line, size_t& pos)
{
  if (pos >= line.length())
    return false;

  // Program name is fixed width, padded with spaces
  size_t start = pos;
  while (pos < line.length() && !std::isdigit(line[pos]))
    pos++;

  if (start == pos)
    return false;

  program_name = line.substr(start, pos - start);
  // Trim trailing spaces
  size_t end = program_name.find_last_not_of(' ');
  if (end != std::string::npos)
    program_name = program_name.substr(0, end + 1);

  skip_whitespace(line, pos);
  return true;
}

bool PwrLogMessage::parse_pid(const std::string& line, size_t& pos)
{
  if (pos >= line.length() || !std::isdigit(line[pos]))
    return false;

  size_t start = pos;
  while (pos < line.length() && std::isdigit(line[pos]))
    pos++;

  try
  {
    pid = std::stoi(line.substr(start, pos - start));
    skip_whitespace(line, pos);
    return true;
  }
  catch (...)
  {
    return false;
  }
}

bool PwrLogMessage::parse_timestamp(const std::string& line, size_t& pos)
{
  // Parse: "25-09-23 14:32:01.00"
  if (pos + 20 > line.length())
    return false;

  std::string timestamp_str = line.substr(pos, 20);
  pos += 20;

  // Simple parsing: YY-MM-DD HH:MM:SS.CC
  if (timestamp_str.length() != 20 || timestamp_str[2] != '-' || timestamp_str[5] != '-' ||
      timestamp_str[8] != ' ' || timestamp_str[11] != ':' || timestamp_str[14] != ':' ||
      timestamp_str[17] != '.')
  {
    return false;
  }

  try
  {
    // Convert YY-MM-DD to YYYY-MM-DD format for time_FormAsciiToA
    int year = std::stoi(timestamp_str.substr(0, 2)) + 2000;
    std::string full_timestamp = "20" + timestamp_str; // Convert YY to 20YY

    // Replace the first two digits with full year
    full_timestamp = std::to_string(year) + timestamp_str.substr(2);

    // Use ProviewR time function to handle timezone correctly (like original code)
    pwr_tStatus sts = time_FormAsciiToA(full_timestamp.c_str(), HUNDRED, GB, &timestamp);

    if (EVEN(sts))
    {
      return false;
    }

    skip_whitespace(line, pos);
    return true;
  }
  catch (...)
  {
    return false;
  }
}

bool PwrLogMessage::parse_message(const std::string& line, size_t& pos)
{
  if (pos < line.length())
  {
    message_text = line.substr(pos);
  }
  return true; // Message can be empty
}

void PwrLogMessage::skip_whitespace(const std::string& line, size_t& pos)
{
  while (pos < line.length() && std::isspace(line[pos]))
    pos++;
}

std::string PwrLogMessage::to_string() const
{
  std::ostringstream oss;
  oss << severity_char << " " << std::setw(16) << std::left << program_name << " " << std::setw(8) << pid
      << " ";

  // Format timestamp
  time_t unix_time = static_cast<time_t>(timestamp.tv_sec);
  struct tm* tm_time = localtime(&unix_time);
  oss << std::setfill('0') << std::setw(2) << (tm_time->tm_year % 100) << "-" << std::setw(2)
      << (tm_time->tm_mon + 1) << "-" << std::setw(2) << tm_time->tm_mday << " " << std::setw(2)
      << tm_time->tm_hour << ":" << std::setw(2) << tm_time->tm_min << ":" << std::setw(2) << tm_time->tm_sec
      << "." << std::setw(2) << (int)(timestamp.tv_nsec / 10000000) << " ";

  oss << message_text;
  return oss.str();
}

